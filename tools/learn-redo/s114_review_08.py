from s114_review_common import *
r=Review('stereopsis-p2')
r.intro=dict(type='intro',title='立體視：左右兩張略不同影像，合成深度',body=['> [!big] 比的是能分多細的前後差，不是有沒有看清字。','','先懂視差與秒角，再比較測驗需要的眼鏡、是否可能偷用單眼線索，最後整理測距與姿勢。'])
r.set(0,'視差，不是光學像差：兩眼位置不同，照片略有差別','''
> [!big] 大腦把左右影像的小差別，解讀成前後深度。

輪流閉眼看近物，物體相對背景的位置會跳。兩眼相隔一段距離，所以同一物體在兩眼成像位置略不同，叫**雙眼視差（binocular disparity）**。

| 立體視需要 | 若不穩定會怎樣？ |
|---|---|
| 兩眼有足夠清楚影像 | 未矯正度數、弱視、單眼嚴重視損會影響 |
| 雙眼對準、能融像 | 明顯斜視／抑制可能破壞比較 |
| 兩眼影像大小相容 | Aniseikonia不等像症：影像大小不同，較難整合 |

小角度間歇性外斜視在控制良好時仍可能有立體視；不能只看病名就判完全沒有。色弱不等於失去立體視，但測驗濾鏡是否可用仍需確認辨認條件。
''')
r.set(1,'40秒角比800秒角精細：數字在量最小視差','''
> [!big] 秒角越小，能察覺的前後差越細。

**Stereoacuity（立體視銳度）**是最小能辨的雙眼視差；**1°＝60′＝3600″**，秒角用″，不是秒鐘的時間。

| 結果 | 怎麼讀？ |
|---|---|
| 40″ | 能察覺較細差別，許多成人可達 |
| 800″ | 只能察覺較粗差別，比40″差 |
| 課堂<60″ | 常用正常精細立體視參考，依年齡、測驗與距離而異 |

課堂題型8Δ間歇性外斜較可能保留；60Δ內斜、45Δ外斜、單眼失明通常較不利，不能用一個角度代替完整功能判斷。頭斜、偷看與單眼線索可讓測驗高估。
''')
r.set(2,'先分兩類：看輪廓，或從亂點裡找形狀','''
> [!big] 亂點沒有明顯輪廓，比較不容易單眼猜中。

| 測驗 | 兩眼怎麼分開影像？ | 特色 |
|---|---|---|
| Titmus蒼蠅／圓圈 | 偏光眼鏡 | 輪廓型、局部線索較多 |
| Random Dot E | 偏光眼鏡 | 亂點E；課堂成人測距可到150 cm，按規格 |
| TNO | 紅綠分色眼鏡 | 亂點全域，較少單眼輪廓線索 |

**Local局部**偏重輪廓部分的對應；**global全域**需把亂點圖整合才找得到目標。亂點可減少特定線索，仍需正確操作，不保證任何情況完全無法猜。
''',extra=[page('不用特殊眼鏡：Lang和Frisby用不同方式製造視差','''
> [!big] 不用分色／偏光眼鏡，不等於不用雙眼。

| 測驗 | 原理 | 用途／限制 |
|---|---|---|
| Lang | 柱狀光柵把不同圖分給兩眼 | 幼兒篩檢方便；傳統版本只有少數離散視差，不能當連續精密閾值測量 |
| Frisby | 圖案印在有厚度板材不同表面，存在真實深度差 | 不需特殊眼鏡；必須控制頭動與距離 |

Lang／Frisby適合不願戴測試眼鏡的幼兒，但仍需理解找圖的任務。Lang版本不同可有不同視差等級，不把「不適合精密量化」誤說成完全沒有數值。
''')])
r.set(3,'選工具：想排除哪種取巧線索？','''
> [!big] 叫得出蒼蠅，不代表測到精細立體視。

| 問題／情境 | 優先考慮 |
|---|---|
| 孩童不肯戴測試眼鏡 | Lang或Frisby等合適版本 |
| 要減少可見輪廓讓單眼猜中的影響 | Random Dot E、TNO等亂點測驗 |
| 題目問不需偏光眼鏡 | Lang、Frisby不用特殊眼鏡；TNO需要的是紅綠分色，不是偏光 |
| Random Dot E操作 | 合適照明、偏光眼鏡、必要的近用矯正，距離依卡片規格 |

「不需偏光」和「完全不需眼鏡」是不同問法。真實深度板若移頭也可能產生單眼運動線索，不能因Frisby不用眼鏡就放任頭動。
''')
r.set(4,'測驗距離、眼鏡與頭位，都是題目條件','''
> [!big] 視差角會隨距離變；同一圖拿近拿遠，不是同一難度。

| 操作 | 為什麼？ |
|---|---|
| 用測驗規定距離 | 不能任意按手長或習慣調整 |
| 戴適當遠／近用矯正 | 先有清楚影像；「不用特殊眼鏡」不等於不用度數矯正 |
| 頭正、視標位置合適 | 頭斜可能改變偏光分離或使用額外線索 |
| 不先偷看可見輪廓 | 避免靠記位置回答 |
| 充足、穩定照明 | 讓圖點與對比正常呈現 |

測距可依**測驗設計**改變，例如特定Frisby階梯測距，但要用對應換算，不能任意移動後照原卡數值記錄。
''')
r.set(5,'結果太好或太差，都先問有沒有測對','''
> [!big] 觀察反應方式，比只抄一個秒角更重要。

| 所見 | 核對 |
|---|---|
| 頭斜看Titmus也答對 | 可能用輪廓／位置線索，改用亂點確認 |
| 忘戴近用矯正，讀不到圖 | 先處理模糊，不直接診斷無立體視 |
| 不斷把板拉近 | 測距變了，需回規範或按規定換算 |
| 色覺異常 | 不直接當沒有立體視；選能可靠完成的測驗 |

記錄測驗名稱、版本／距離、矯正與最好可辨秒角；不同測驗測得的數字不必完全相等。
''')
r.save()

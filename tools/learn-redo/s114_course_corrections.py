RULES={a:b for a,b in RULES.items() if a!=b}
def fixed(v):
 if isinstance(v,str):
  for a,b in RULES.items():
   # Some clarified phrases retain the original words. Protect an already-fixed
   # phrase so rerunning does not add the same qualifier again.
   v=b.join(part.replace(a,b) for part in v.split(b)) if a in b else v.replace(a,b)
  return v
 if isinstance(v,list):return [fixed(x) for x in v]
 if isinstance(v,dict):return {k:(x if k in ('q','front','id','choices') else fixed(x)) for k,x in v.items()}
 return v
def run():
 manifest=ROOT/'tools/learn-redo/s114-course-corrections.json'
 records=[];d=plan()
 for name in dict.fromkeys(e['unit'] for e in d['lessons']):
  path=ROOT/FOLDER/(name+'.json');p=json.loads(path.read_text(encoding='utf-8'))
  lids={e['lesson'] for e in d['lessons'] if e['unit']==name}
  for li,l in enumerate(p['lessons']):
   if l['id'] not in lids:continue
   def walk(v,trail):
    if isinstance(v,str):
     after=fixed(v)
     if v!=after:records.append(dict(unit=name,lesson=l['id'],path=trail,before=v,after=after))
     return after
    if isinstance(v,list):return [walk(x,trail+[i]) for i,x in enumerate(v)]
    if isinstance(v,dict):return {k:(x if k in ('q','front','id','choices') else walk(x,trail+[k])) for k,x in v.items()}
    return v
   p['lessons'][li]=walk(l,['lessons',li])
  source=raw(name).splitlines()[1];indent=len(source)-len(source.lstrip())
  path.write_text(json.dumps(p,ensure_ascii=False,indent=indent)+'\n',encoding='utf-8')
 previous=json.loads(manifest.read_text(encoding='utf-8')) if manifest.exists() else []
 if records or previous:
  packs={name:json.loads((ROOT/FOLDER/(name+'.json')).read_text(encoding='utf-8')) for name in dict.fromkeys(r['unit'] for r in previous+records)}
  def current(r):
   v=packs[r['unit']]
   try:
    for k in r['path']:v=v[k]
    return v==r['after']
   except (KeyError,IndexError,TypeError):return False
  merged={(r['unit'],json.dumps(r['path'])):r for r in previous+records if current(r)}
  manifest.write_text(json.dumps(list(merged.values()),ensure_ascii=False,indent=2)+'\n',encoding='utf-8')

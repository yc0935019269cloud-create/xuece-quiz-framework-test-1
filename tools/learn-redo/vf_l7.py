from optometry_common import *
r=Rewrite('optom2-u3-vf','l7')
r.set(0,'從眼底到腦後：先認一條路線','''
> [!big] 鼻側網膜跨到對面；顳側網膜留在同側。

::: flow
視網膜 Retina：眼底接光
視神經 Optic nerve：每眼訊號各自離開
視交叉 Optic chiasm：鼻側纖維交叉
視徑 Optic tract：收兩眼同一半邊世界的訊號
外側膝狀核 LGN：丘腦的中繼站
視放射 Optic radiation：纖維向後展開
枕葉初級視覺皮質：腦後的視覺處理區
:::

不是兩隻眼的訊號全部交換。只有**鼻側網膜**纖維交叉，顳側不交叉；所以一邊腦最後接到的是**兩眼同一側視野**。
''',image=True)
r.set(1,'右邊世界，為什麼由左邊腦接手？','''
> [!big] 光學影像左右反、上下倒；傳訊線再依半邊世界合流。

| 同一個右側物體 | 落在哪裡？ | 往哪傳？ |
|---|---|---|
| 右眼看它 | 右眼鼻側網膜 | 視交叉跨到左邊 |
| 左眼看它 | 左眼顳側網膜 | 留在左邊 |
| 最後 | 兩眼訊號合流 | **左視徑帶右視野** |

| 視放射分路 | 訊號來自 | 代表哪裡？ |
|---|---|---|
| 顳葉Meyer's loop（繞行的彎路） | 下方網膜 | 上方視野 |
| 頂葉背側視放射 | 上方網膜 | 下方視野 |

例如右顳葉受損，可少掉兩眼的**左上**象限。兩側枕葉視覺皮質嚴重受損可致皮質性失明；瞳孔光反射線路在更前面分出，仍可能保留。
''')
r.set(2,'三個定位問題：一眼？外側？同一側？','''
> [!big] 「同名」是同一側世界，不是病灶與缺損同側。

| 看到的缺損 | 優先想哪一段？ |
|---|---|
| 只有一眼 | 視交叉前：網膜、視神經 |
| 兩眼各少靠耳側的一半 | 視交叉中央：雙顳側半盲 |
| 兩眼都少世界的右半 | 左邊視交叉後路徑 |
| 兩眼都少世界的左半 | 右邊視交叉後路徑 |

越往後、越接近枕葉，兩眼缺損形狀**通常**越一致，叫一致性較高；這是定位線索，並非絕對法則。
''',image=True)
r.set(3,'上、下象限：先翻成對側，再選顳葉或頂葉','''
> [!big] 上方缺損想顳葉；下方想頂葉；左右取對側。

| 視野缺損 | 典型定位 |
|---|---|
| 兩眼右上象限 | 左顳葉Meyer彎 |
| 兩眼右下象限 | 左頂葉視放射 |
| 兩眼右半＋中央仍保留 | 左枕葉病灶線索 |
| 單眼鼻側半盲 | 可見同側視交叉外側受壓；也需排除其他眼部原因 |

**黃斑保留（macular sparing）**＝半盲中注視附近仍保留。常見於枕葉病灶；**PCA（後大腦動脈）**梗塞是典型原因之一。

同名性視野缺損常尊重垂直中線；視徑病灶兩眼形狀可較不一致。
''')
r.set(4,'A～G：在路線上標出斷在哪裡','''
> [!big] 先看圖上的左／右標示，再對缺損。

| 圖號 | 受損點 | 典型結果 |
|---|---|---|
| A | 左視神經 | 左眼全盲 |
| B | 視交叉中央 | 雙顳側半盲 |
| C | 視交叉左外側 | 左眼鼻側半盲 |
| D | 左視徑 | 右同名性半盲 |
| E | 左顳葉Meyer彎 | 右上象限盲 |
| F | 左頂葉 | 右下象限盲 |
| G | 左枕葉 | 右半盲，可有黃斑保留 |

回看前頁的路徑圖比對，別只背英文字母；A～G只屬這份圖例。
''')
r.set(5,'把病因接到位置，保留「可能」兩個字','''
> [!big] 位置解釋型態，病因還需要其他檢查確認。

| 位置 | 課堂典型原因與關係 |
|---|---|
| 視交叉中央B | 腦下垂體在下方；腫瘤往上壓交叉纖維 →雙顳 |
| 視交叉外側C | 鄰近內頸動脈；課堂以血栓等血管病變壓迫作典型題型 →同側鼻側 |
| 左顳葉E | 右上象限「pie in the sky」：像天空少一角 |
| 左枕葉G | PCA梗塞→右半盲；中央可保留 |

中央保留可與枕極不同血流供應／側枝等因素相關，**不是所有人都固定有同樣雙重供血**。單側枕葉病灶造成對側缺損；皮質性失明通常需雙側廣泛視覺皮質損害，不把兩者混成同一件事。
''')

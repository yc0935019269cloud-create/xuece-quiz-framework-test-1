from optometry_common import *
r=Rewrite('optom2-u4-bb','l4')
r.set(0,'交替遮蓋：同一行字，左右眼輪流看','''
> [!big] 清楚那眼加正；這次是輪流，不是同時看上下兩行。

**Successive alternate occlusion（連續交替遮蓋，SAO）**用遮眼板，病人記住上一眼的清楚程度，再和另一眼比。

| 順序 | 課堂做法 |
|---|---|
| 1 | 20/50視標；雙眼先各＋1.00 D霧視 |
| 2 | 遮左看右，再遮右看左 |
| 3 | 較清楚眼加＋0.25 DS |
| 4 | 重比，直到最接近一樣 |
| 5 | 移除遮蓋，雙眼等量去霧至MPMVA |

**Occluder＝遮眼板**。因任何時刻只有一眼看，沒有雙眼融像，課堂說較少使用。
''')
r.set(1,'交替遮蓋的限制：少了共同影像，還要記前次','''
> [!big] 遮一眼會變不穩，或記不住前一次，就換方法。

| 需要留意 | 理由 |
|---|---|
| 遠視 | 調節可能藏住正度數 |
| 屈光不等 | 兩眼原始條件不同，直接輪流比較可能不穩 |
| 隱性眼球震顫 | 遮蓋可能加重眼動 |
| 最佳視力差、短期記憶弱 | 模糊比較不一定有意義或可完成 |

課堂列它為非融像性方法，雙眼霧視量也可採＋0.75 D。**Humphriss不拿遮眼板輪流遮**；下一頁是用模糊來降低另一眼中央干擾。
''')
r.set(2,'Humphriss：一眼糊一點，仍保留周邊一起看','''
> [!big] 不遮掉另一眼，而是用正鏡暫時降低它的中央清楚度。

**Humphriss immediate contrast／blurring technique（即時對比／霧視法）**：兩眼睜開，非受測眼常加＋1.00 D霧視；受測眼比較紅綠或球面鏡片。

| 紅綠測試：受測眼反應 | 調受測眼S |
|---|---|
| 紅底字較清楚 | −0.25 D |
| 綠底字較清楚 | ＋0.25 D |
| 一樣清楚 | 球面確認終點 |

未測眼仍能提供周邊融像鎖，所以不是完全遮蓋。最佳視力稍不等時，可評估改良單眼霧視版本。
''')
r.set(3,'Humphriss換眼：先糊剛測好的，再放開下一眼','''
> [!big] 每次都有一眼提供周邊線索，另一眼作答。

| 步驟 | 右眼OD | 左眼OS |
|---|---|---|
| 測右眼 | 比紅綠，微調S | 加＋1.00 D霧視 |
| 換測左眼 | 暫加＋1.00 D霧視 | 移除原暫加霧視，比紅綠 |
| 兩眼比較完成 | 兩眼按課堂流程霧視，再等量去霧至雙眼MPMVA | 同左 |

採半暗室；理想紅綠同樣清楚。課堂在不能相同的年輕人情境，可取「最少負、綠稍清楚」，不能用多餘負鏡一路逼清楚。

課堂將遠視、震顫列為此流程限制，需評估完整雙眼驗光。不是每個人都能穩定回答紅綠；也不把鏡片「各固定呈現1秒」當通用規則。
''')
r.set(4,'稜鏡分離紅綠：每眼各自比兩種底色','''
> [!big] 不比左右眼誰清楚，所以較能處理兩眼視力不等。

同一紅綠視標被稜鏡分成兩行：

| 本課放法 | 病人比較 | 調哪眼？ |
|---|---|---|
| 右眼3Δ BU，看下行 | 下行裡，紅底字或綠底字清楚？ | 右眼S |
| 左眼3Δ BD，看上行 | 上行裡，紅底字或綠底字清楚？ | 左眼S |

例如右眼最佳視力1.0、左眼0.8，不能要求兩行字同樣清楚；但每眼仍可能判斷**自己的紅綠差別**。

適用的前提是能看見並比較視標，並非任何嚴重病變造成的視力不等都必須做。
''')
r.set(5,'稜鏡紅綠走一次：先分行，再各比紅綠','''
> [!big] 分離靠稜鏡；紅綠濾片負責呈現不同底色。

| 順序 | 課堂做法 |
|---|---|
| 1 | 雙眼各＋0.75 D霧視 |
| 2 | 選比較差眼閾值大一行的紅綠視標 |
| 3 | OD3Δ BU、OS3Δ BD；先確認上下行對應 |
| 4 | 兩眼睜開；下行紅綠調OD，上行紅綠調OS |
| 5 | 紅清楚加負，綠清楚加正；確認各眼終點 |
| 6 | 移除稜鏡；課堂再雙眼霧視約＋1.00、等量去霧至MPMVA |

**red-green filter（紅綠濾片／紅綠視標）**讓字落在兩種色底，不是拿紅綠眼鏡代替稜鏡分左右眼。

兩眼同時開著，依序詢問各行；不是把另一眼遮掉重新做完整單眼驗光。
''')
r.set(6,'偏光與隔板：中央分給不同眼，周邊仍有共同圖像','''
> [!big] 分開「哪眼看哪部分」，同時保留融像線索。

| 方法 | 分開視標的方式 | 保留什麼？ |
|---|---|---|
| Polaroid／Vectograph 偏光 | 兩眼透過不同方向偏光濾片，各見指定部分 | 共同融像刺激 |
| Septum／TIB隔板 | 中間隔板讓兩眼各看指定區域 | 周邊共同影像 |

目的仍是確認兩眼調節反應／需求一致；有融像較自然，但準確度依方法、病人與操作，不是只要偏光就一定勝過所有方法。
''')
r.set(7,'TIB與Worth四點：名稱相近，目的不同','''
> [!big] 平衡用來調球面；抑制檢查是在問某眼訊號有沒有被忽略。

| 名稱 | 這裡要記 |
|---|---|
| Turville's infinity balance，TIB | 隔板平衡，保周邊融像，可搭紅綠，也需合適霧視 |
| 偏光平衡 | 各眼看到視標一部分，藉比較調球面 |
| Worth 4 dot，魏氏四點 | 評估融像、抑制或複視等，不是拿來完成球面平衡 |

**抑制 suppression**是腦忽略其中一眼的部分訊號。偏光也可設計其他測試，但本課的**偏光平衡法目的不是查抑制**。
''')

r.before=[page('檢影在看什麼：瞳孔裡回來的光','''
> [!big] 驗光師掃光帶，看眼內反光怎麼走，不靠病人選1或2。

**Retinoscopy＝視網膜檢影**，屬他覺／客觀驗光。**反射光（reflex）**是從眼底返回、在瞳孔看到的亮區。

| 名詞 | 指的是誰？ |
|---|---|
| WD，working distance | 病人到檢影鏡的工作距離 |
| WL，working lens | 補償有限工作距離的正球鏡力量 |
| 毛值 Gross | 在這距離把反光中和所需的總鏡片度數 |
| 淨值／Rx | 扣好工作距離後的遠用結果 |

中和就是回光達到檢查者所在位置的條件；不等於眼睛必然正視。
''')]
r.set(0,'為什麼扣WL：檢查者站在有限距離','''
> [!big] 毛值裡有工作距離需要的正力量，遠用結果要扣掉它。

| WD | 換成m | WL＝1/WD |
|---|---|---|
| 80 cm | 0.80 | ＋1.25 D |
| 約67 cm | 約0.667 | ＋1.50 D |
| 約57 cm | 約0.571 | ＋1.75 D |
| 50 cm | 0.50 | ＋2.00 D |

公式：**Rx＝未扣補償的毛值−WL**。WL用正數；減正數之後，結果會更負／較少正。

若專門WL已另外放好、而讀數只記其餘鏡片，讀到的可能已是淨值；先認紀錄包含什麼，不能再扣第二次。
''')
r.set(1,'兩方向先各扣，再寫成球柱處方','''
> [!big] 同樣的WL扣兩條，兩方向的差不會變。

例：WD50 cm；180°毛值＋0.75、90°毛值−3.00 D。

| 方向 | 各扣2.00 D | 淨值 |
|---|---|---|
| 180° | 0.75−2.00 | −1.25 D |
| 90° | −3.00−2.00 | −5.00 D |

負柱鏡寫法：較正的−1.25當S；C＝−5−(−1.25)＝−3.75；軸在180°，所以 **−1.25／−3.75 ×180**。

戴CL（contact lens，隱形眼鏡）檢影，先算剩餘的**超額驗光**，再按題目近似加回原CL度數。直接由無加鏡的遠點距離求近視時，用**−1/d（m）**；這種直接遠點法不要又當毛值重扣WL。
''')
r.set(2,'順動和逆動：和你掃光帶的方向比','''
> [!big] 同向叫順動，反向叫逆動；先確認平面鏡模式。

WD50 cm時，WL＝2.00 D。沒有另放補償、調節放鬆時：

| 原眼情況 | 回光動向 | 為了中和試加 |
|---|---|---|
| 遠視、正視、近視<2.00 D | 順動With | 正鏡 |
| 近視＝2.00 D | 中和 | 此時不另加鏡即可中和 |
| 近視>2.00 D | 逆動Against | 負鏡 |

可用實在眼前的近視遠點理解：**遠點比檢查者更遠→順；位於病人和檢查者之間→逆；剛在檢查者處→中和**。遠視的虛遠點在眼後，不能當成正距離直接比FP>WD。
''')
r.set(3,'變模式會反向；移動鏡片也叫順逆，但不是同一題','''
> [!big] 先看你是在掃檢影光，還是在晃眼鏡片。

| 題目操作 | 判讀 |
|---|---|
| 平面鏡／發散照明檢影 | 順動加正，逆動加負 |
| 收斂照明／凹面鏡模式 | 動向與平面鏡反過來 |
| 手動晃一片鏡片，看物體影像 | 負鏡影像順移，正鏡影像逆移；不是瞳孔反光 |

課堂機型把套筒向上與收斂模式相連；換不同檢影鏡先確認機型，不能把上下方向當所有產品通用。

例：平面模式、WD50 cm，−1.75 D近視比WL2.00稍小→**接近中和的快速順動**；不是只要近視就一定逆動。
''')
r.set(4,'接近中和：更快、更亮、更寬','''
> [!big] 快亮寬表示接近，不是病人視力突然變好。

| 所見反光 | 怎麼想？ |
|---|---|
| 越靠近中和，快、亮、寬 | 用小步鏡片細查終點 |
| 中和時瞳孔大面積亮起、看不出方向 | 找到該距離條件下的中和 |
| 中央順、周邊逆 | 課堂典型球面像差題型，不直接等於圓錐角膜 |
| 暗、扭曲或剪刀樣 | 可涉及介質混濁、像差、不規則角膜等，還需檢查 |

**球面像差**是中央與周邊光線聚焦不同；**介質混濁**例如白內障使透光、回光受影響。不同圖樣是線索，不是單一確診。
''')
r.set(5,'檢影的用途：看不會回答的人，也能先估度數','''
> [!big] 客觀不代表不受配合與調節影響。

| 適用／觀察用途 | 要注意 |
|---|---|
| 孩童、溝通困難者 | 不需要比較「哪片清楚」，仍要控制注視與調節 |
| 隱性遠視、懷疑非器質性視力下降 | 提供客觀線索，不能只靠檢影判裝病 |
| 不規則角膜 | 反光可能提供線索，常需其他檢查 |
| 客觀測散光 | 檢影可；鐘面圖、JCC、裂孔板比較屬自覺式 |

讓病人看**遠方、大而可見的視標**，課堂可配指定紅綠濾鏡；檢查者的頭別擋住視線，免得改看近物而用力調節。超音波主要量結構／長度，不能替代檢影直接得散光處方。
''')

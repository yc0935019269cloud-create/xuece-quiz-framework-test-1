from optometry_common import *
r=Rewrite('optom2-u4-bb','l5')
r.set(0,'雙眼驗光：整段驗光都保留兩眼觀看','''
> [!big] 不只是最後平衡球面，而是在雙眼條件下完整驗。

**Binocular refraction（雙眼驗光）**：一眼中央被霧視、另一眼做球面與散光；兩眼持續睜開，仍保周邊融像鎖。

| 可能幫上忙的情境 | 原因 |
|---|---|
| 遠視、假性近視 | 更穩定控制調節，少把額外用力混進處方 |
| 屈光不等 | 在較自然雙眼狀態評估 |
| 隱性眼球震顫 | 不完全遮一眼，可能較穩 |
| 單眼與雙眼軸位不同 | 在實際雙眼條件重新細修 |

可能取得更合適的軸與度數，不是保證每位病人都一定比單眼法準。
''')
r.set(1,'能不能做：兩眼都要看得見，也要能分辨測哪眼','''
> [!big] 優勢眼干擾太強時，另一眼的回答可能不可信。

| 條件／名詞 | 意思 |
|---|---|
| 課堂前提 | 檢影後，兩眼視力都≥20/25（0.8） |
| Dominant eye 優勢眼／利眼 | 雙眼觀看時較主導的眼；不單等於視力數字較好 |
| Non-dominant eye 非優勢眼 | 相對較不主導的眼 |
| 兩眼主導反應差很多 | 霧視後仍可能由優勢眼搶答，不宜硬做 |

有雙眼視覺問題時可評估，但須確認能保有有效融像。白內障不會因改成雙眼驗光就恢復透明，所以不是此法使屈光度更精確的典型適應情境。
''')
r.set(2,'一眼負責保穩定，另一眼完成整套','''
> [!big] 被霧視的是非受測眼，不是要測的那眼。

| 時間 | 右眼OD | 左眼OS |
|---|---|---|
| 先測右 | 初始球面 →JCC →微調球面 | 霧視到約20/50，仍睜開 |
| 換測左 | 暫加約＋1.00 D霧視 | 移除原霧視，做完整驗光 |
| 結尾 | 雙眼都霧視，再一起去霧至MPMVA | 同左 |

**完整**代表球面S、散光軸、柱鏡C都在這個雙眼觀看條件下檢查；不只是微調0.25 D球面。
''')
r.set(3,'換眼時先確認：哪片是暫加霧視？','''
> [!big] 霧視片會加回、拿掉；驗好的處方不要跟著清空。

課堂操作拆成六步：

1. 檢影後裝好起始處方，OS霧視到約20/50。
2. OD完成初始球面、JCC、微調球面。
3. OD保留剛驗好的處方，再暫加＋1.00 D。
4. OS移除先前暫加的霧視，做同樣完整檢查。
5. OS保留驗好結果，再暫加＋1.00 D，使雙眼都霧視。
6. 兩眼等量少正／加負，找雙眼MPMVA。

MPMVA＝最好視力下最多正／最少負球面。每次換眼都確認病人看的確是受測眼資訊，並保周邊融像。
''')
r.set(4,'雙眼平衡與雙眼驗光：看有沒有重新驗散光','''
> [!big] 只修最後球面是平衡；整段含散光是雙眼驗光。

::: cols b o
### 雙眼平衡
單眼MSR已完成，柱鏡與軸保留。
再調兩眼球面需求，最後雙眼MPMVA。
|||
### 雙眼驗光
檢影後，以雙眼觀看條件取代單眼MSR段。
球面、JCC軸與度數、微調都做。
:::

兩者都可能「兩眼睜開」，光看這句不能判斷是哪一種。
''')
r.set(5,'比較表：時間點、內容、目的','''
> [!big] 課堂名稱分清楚，排序題就不會放錯位置。

| 比較 | 雙眼平衡 | 雙眼驗光 |
|---|---|---|
| 在哪時候 | 單眼完整驗光之後 | 檢影後的完整自覺驗光段 |
| 球面S | 微調 | 完整檢查 |
| 散光C與軸 | 保留，不在此重找 | 在雙眼條件下驗 |
| 直接目的 | 平衡調節刺激／需求 | 保融像，取得合適完整屈光結果 |

所以「單眼MSR後做雙眼平衡，和雙眼自覺式驗光相同」是錯的。不要因名稱都有雙眼，就把兩個步驟合併。
''')

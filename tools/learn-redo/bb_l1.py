r.before=[page('先懂調節、內聚、融像三個詞','''
> [!big] 對焦、轉眼、把兩眼影像合起來，是三件相關的工作。

| 名字 | 身體在做什麼？ |
|---|---|
| {b:調節 Accommodation} | 眼內水晶體改變形狀、增加對焦力量 |
| {o:內聚 Convergence} | 兩眼向鼻側轉，對準同一個近物 |
| {g:融像 Fusion} | 把兩眼看到的影像整合成一個 |

看近時這些工作常互相配合。驗光不只找「讀得到字的鏡片」，也要避免一眼被迫承受不合適的對焦需求。
''')]
r.set(0,'雙眼平衡：單眼都驗完，再一起確認','''
> [!big] 調的是兩眼對焦需求的平衡，不是把度數變一樣。

::: flow
檢影：先估起始度數
MSR：一眼一眼找球面、散光，再確認球面
雙眼平衡 Binocular balance：在雙眼條件下微調球面
:::

| 這一步會改 | 這一步先保留 |
|---|---|
| 球鏡 S，常每次0.25 D | 已驗好的柱鏡 C 與軸位 |

課堂把目的稱為**讓兩眼調節相等、用眼舒適**；操作上是平衡兩眼的調節刺激／需求，不是分別命令左右水晶體各用不同力量。
''')
r.set(1,'不是平衡視力、瞳孔，或眼位','''
> [!big] 兩眼讀同一行，只是比較條件；目的仍是對焦需求。

| 容易誤選的目的 | 為什麼不對？ |
|---|---|
| 讓兩眼視力一樣 | 病變造成的視力差，不能靠多加鏡片硬拉平 |
| 讓瞳孔一樣大 | 不是球面微調的目標 |
| 影像大小一樣 | 不是這項平衡的直接測量 |
| 測眼外肌／隱斜位量 | 要用眼位相關檢查 |

**隱斜位**是融像打開後才顯出的眼位偏移；遮蓋測試、Maddox rod（馬竇氏鏡）、von Graefe等才在評估這類問題。

另一個目的，是在較自然的雙眼狀態下，再確認處方。
''')
r.set(2,'周邊融像鎖：中央在比較，周圍仍一起看','''
> [!big] 有共同周邊影像，能幫眼睛維持穩定觀看。

想像看遠方一行字。即使暫讓一眼中央變模糊，它仍可能看見周圍的大輪廓，兩眼靠共同輪廓維持對位。

| 名詞 | 在這裡代表什麼？ |
|---|---|
| Peripheral fusion，周邊融像 | 兩眼共同周邊輪廓可整合 |
| Fusion lock，融像鎖 | 保留這些共同線索，幫忙穩定眼位與調節刺激 |
| 固定內聚 | 對準同一遠方目標，觀看距離不一直變 |

這是穩定線索，**不是把眼球鎖死，也不保證所有人調節完全歸零**。
''')
r.set(3,'為什麼保留雙眼觀看，可能比遮一眼穩？','''
> [!big] 少了共同影像，有些人的對焦或眼動會更不穩。

::: cols b o
### 保留周邊融像
一眼提供穩定觀看線索，另一眼逐步微調。
部分病人調節較放鬆，較不容易把遠視藏起來。
|||
### 完全遮一眼
共同線索消失，部分人的調節較波動。
尤其**隱性眼球震顫**可能因遮蓋而加重。
:::

**眼球震顫**是眼睛不自主反覆動。不是所有類型都必然因遮一眼變差；課堂是在強調選擇保有融像方法的理由。
''')
r.set(4,'誰適合：看調節與可比較性，別只看年齡','''
> [!big] 度數一樣，也不能直接判定不需要平衡。

| 條件 | 怎麼想？ |
|---|---|
| 仍有調節、雙眼可穩定比較 | 依流程做平衡，即使兩眼度數／視力相同 |
| 已無實質調節能力 | 調節平衡的必要性降低；課堂常以約60歲以上舉例 |
| 黃斑等病變，兩眼最佳視力差很大 | 不宜用「兩眼霧後同樣清楚」的方法硬拉平 |
| 稍不等但能做紅綠比較 | 可評估改良Humphriss／稜鏡分離紅綠等方法 |

60歲只是課堂情境，**不是生日一到就一律免做**。明顯病理視力差與輕微差異也要分開。
''')
r.set(5,'兩邊一樣糊，不代表最後處方已經好','''
> [!big] 平衡完成後，還要雙眼一起找 MPMVA。

兩眼都霧視到同樣模糊，只能說目前比較結果接近；可能還多了相同正度數，或兩眼都不在最合適球面。

| 接續動作 | 目的 |
|---|---|
| 移除分離工具 | 回到兩眼共同看一個視標 |
| 兩眼等量、慢慢減正／加負 | 去掉暫加霧視，保留兩眼差值 |
| 找雙眼MPMVA | 最佳視力下最多正／最少負球面 |

因此平衡≠完全矯正。不能把「視力平衡」誤當目的，也不能做到一樣糊就讓病人直接戴走。
''')

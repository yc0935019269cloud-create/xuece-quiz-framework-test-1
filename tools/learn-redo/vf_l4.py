from optometry_common import *
r=Rewrite('optom2-u3-vf','l4')
r.set(0,'SAP：看見閃光就按，電腦測每點要多亮','''
> [!big] 眼睛盯中央；光點在旁邊閃，看到才按。

**SAP＝standard automated perimetry，標準自動視野檢查**。一般用固定大小的白光點，位置固定、亮度逐次改變，測各位置的**閾值（剛能察覺的強度）**。

| 準備 | 理由 |
|---|---|
| 固定注視點 | 轉眼追光就改了受測位置 |
| 使用儀器建議的近距離矯正 | 碗面約30 cm等有限距離，遠用度數不一定合適 |
| 校正眼位、鏡片、瞳孔條件 | 避免外物擋住或額外模糊 |

度數依儀器設定、年齡與調節能力決定，不能所有人都一律加同一片近用鏡。
''')
r.set(1,'30-2、24-2、10-2：測哪裡、點有多密？','''
> [!big] 較小的中央範圍，可以用更密的點查細節。

| 儀器／程式 | 範圍或間距 |
|---|---|
| Medmont Central | 中央30° |
| Medmont Glaucoma | 鼻側可延伸到50° |
| Medmont Macula | 中央10° |
| Humphrey 30-2／24-2 | 中央約30°／24°；24-2鼻側有延伸；點距約6° |
| Humphrey 10-2 | 中央10°，點距約2° |

後面的 **-2 是測點排列命名**，不是視力或少2度。10-2 可細看黃斑、晚期青光眼剩下的中央島。

瞳孔太小會使結果下降。可靠度門檻依策略與報告而異；國考舊題將偽陽性10%視為仍可接受，不要說「任何偽陽性就無效」。
''')
r.set(2,'dB 高：很暗的光也看得到','''
> [!big] dB 記的是光被減弱多少，不是把光加亮多少。

以 Humphrey 白光檢查為例，**0 dB＝最大亮度10,000 asb**；40 dB 時，刺激已減到1 asb。

::: cols b o
### 40 dB 還看見
很暗也能察覺 →該點敏感度高。
40 dB 是年輕中央高敏感度的示例，不是所有位置都該40。
|||
### 0 dB 都沒看見
最大刺激也無反應 →該點屬檢測範圍內的**絕對暗點**。
「0 dB的刺激」本身不等於「已證明看不見」。
:::

**Apostilb（asb）**是亮度的絕對單位；dB 是相對儀器最大刺激的單位，不同機器數值不能直接比。
''')
r.set(3,'每10 dB，光弱十倍：一步一步讀表','''
> [!big] 先從10,000開始，每增加10 dB就除以10。

| 減弱量 | Humphrey白光刺激亮度 |
|---|---|
| 0 dB | 10,000 asb |
| 10 dB | 1,000 asb |
| 20 dB | 100 asb |
| 30 dB | 10 asb |
| 40 dB | 1 asb |
| 50 dB | 0.1 asb（此尺度的更暗端） |

**10 dB＝1個log單位**，這裡就是十倍比值。公式是 **亮度＝10,000÷10^(dB/10)**；先懂「十倍」再用公式。

正常敏感度仍要和**同年齡、同位置**比；不是dB越高到任何程度都越可靠，也不是所有機型最暗都停在40。
''')
r.set(4,'讀報告的順序：先可信，再看缺損','''
> [!big] 一張很黑的圖，先別急著判病。

| 順序 | 找哪裡？ | 問什麼？ |
|---|---|---|
| 1 | 可靠度：固視遺失、偽陽性、偽陰性 | 有沒有盯好？有沒有亂按／漏按？ |
| 2 | 數字圖、灰階圖 | 哪些位置敏感度低？ |
| 3 | 總差值 TD | 和同年齡正常人差多少？ |
| 4 | 模式偏差 PD（課堂稱趨勢偏差） | 扣掉整體高度偏移，哪裡局部更差？ |
| 5 | MD、PSD、VFI、GHT | 整體、形狀與上下對稱如何？ |

**PD不是時間趨勢圖**；要追蹤變化仍須比較多次報告。旁圖保留一張完整報告，先照表定位區塊即可。
''',image=True)
r.set(5,'TD 與 PD：全班比較，和調整整體後再比','''
> [!big] TD 看整體＋局部；PD試著凸顯局部。

| 區塊 | 正式意思／讀法 |
|---|---|
| 原始數字 dB | 這次該點閾值 |
| 灰階 | 直觀看深淺，不等於統計機率 |
| Total deviation，TD 總差值 | 每點減去同齡同位置正常值 |
| Pattern deviation，PD 模式偏差／趨勢偏差 | 用自身較保留點估整體高度偏移後校正，再與常模比 |
| 機率圖 | 比常模異常的稀有程度，常有<5%、<2%、<1%、<0.5%符號 |

機率符號越黑，代表這種低值在正常參考群越少見，**不是患某疾病的機率**。

MD（平均偏差）看整體；PSD看局部不規則；兩者是**整體指標，不是可靠度指標**。VFI與GHT後面會拆開解釋。
''')
r.set(6,'白內障像蒙霧：很多位置一起下降','''
> [!big] 如果整體一起變暗，TD常差，PD可能接近正常。

**介質**是光進眼睛會穿過的透明部分，例如角膜、水晶體。白內障是水晶體混濁，會減弱、散射光。

| 同一份報告 | 可能看到 |
|---|---|
| TD：和正常人比 | 許多位置一起下降 |
| PD：調整整體偏移後 | 若主要是普遍下降，可接近正常 |

PD有助區分瀰漫下降與局部缺損；**PD正常不能單獨證明只有白內障**，嚴重損害時PD也有侷限，仍要配合眼部檢查。
''',image=True)
r.set(7,'先排掉可修正的干擾，再判視神經','''
> [!big] 白內障、屈光未矯正、遮擋，都可能讓圖變差。

| 條件 | 可能影響／處理 |
|---|---|
| 沒有適當近用矯正 | 普遍模糊；按儀器與病人需求補正 |
| 瞳孔過小 | 敏感度下降，需記錄與評估 |
| 眼瞼下垂 | 可能擋上方視野 |
| 操作不熟練 | 定位、指導或鏡框遮擋出錯 |
| 白內障合併青光眼 | TD廣泛下降之上，PD可能仍留下弓形缺損 |

舊國考在特定選項中把外斜視列為「不是常見檢查誤差因素」；不要延伸成斜視病人完全不必注意固視與眼位。
''')
r.save()

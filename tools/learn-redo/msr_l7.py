from optometry_common import *
r=Rewrite('optom2-u2-msr','l7')
r.before=[page('這課的三個時間點','''
> [!big] 檢影後先調一次球面，散光調完再確認一次。

| 時間 | 做什麼？ | 目的 |
|---|---|---|
| 檢影後 | 初始球面 | 讓整體對焦先到合適位置 |
| 初始球面附近 | 紅綠測試 | 用兩色的清晰度幫忙查球面 |
| JCC 後 | 微調球面／第二次 MPMVA | 防止調散光時，球面偏掉 |

**MPMVA**＝最好視力下，最多正球鏡／最少負球鏡。**Over-minus**＝負鏡給過多，病人可能用額外調節把它補回。
''')]
r.set(0,'檢影做完，先移除工作距離的補償','''
> [!big] 檢影近距離用的工作鏡片，不是最後要配的度數。

檢影鏡不是站在無限遠處看病人，會用到**工作距離補償**。若過程另加了工作鏡片，結束時要按課堂流程，**兩眼同時移除**；已扣除的淨結果不能又扣一次。

| 接著做 | 怎麼做？ |
|---|---|
| 保留檢影得來的散光 | 先調球面 S，不重頭搜尋 |
| 比較球面 | 可從加正鏡放鬆開始，再小步比較 |
| 接近終點 | 每組先較負、後較正；問「清楚」，不問「黑不黑」 |
| 確認 | ＋1.00 D 檢查，必要時紅綠測試 |

這是**初始球面**，終點仍是 MPMVA。
''')
r.set(1,'＋1.00 D 檢查：故意讓它糊，看看降多少','''
> [!big] 已經對好焦的眼睛，加正鏡後看遠應變糊。

| 原本處於最好視力，再加＋1.00 DS | 怎麼理解？ |
|---|---|
| 約降至 20/60（0.3） | 符合課堂預期的失焦量 |
| 只降一點 | 可能原先給太負，這片正鏡先抵消了多餘負度數 |

這只是**輔助檢查**，降幅會受瞳孔、起始視力與眼部狀態影響，不能單憑這一項保證完全沒有 over-minus。

**霧視**也是加正鏡，常＋1.00～＋1.50 DS、視力約 0.3～0.5；讓對焦落在網膜前，協助放鬆調節。負鏡片（凹透鏡）反而會刺激調節。

有些流程先完成兩眼初始球面再做 JCC；課堂亦提及意見不同，辨認題目所採流程即可。
''')
r.set(2,'紅綠：用兩種顏色的焦點，夾住視網膜','''
> [!big] 綠光先聚焦，紅光稍後聚焦。

**色像差**：同一眼睛對不同顏色的收光力量稍有差異。想像兩個前後位置：前面是綠光焦點，後面是紅光焦點。

| 哪邊的黑字較清楚？ | 在典型球面判讀中 | 試調 S |
|---|---|---|
| {r:紅底} | 紅焦點較靠近網膜，整組偏前 | 加 **−0.25 D**，使焦點往後 |
| {g:綠底} | 綠焦點較靠近網膜，整組偏後 | 加 **＋0.25 D**，使焦點往前 |
| 一樣清楚 | 網膜大致在兩色焦點之間 | 可作球面確認終點 |

所以「紅加負、綠加正」是**看完清晰度後，改球鏡**；不是加同色鏡片，也不是改散光。
''')
r.set(3,'怎麼問紅綠，結果才比較可信？','''
> [!big] 比的是黑字清晰度，不是辨認底色。

| 設定 | 為什麼？ |
|---|---|
| 字比剛好讀不出的閾值大一些（超閾值） | 讓病人有字可以比較 |
| 半暗室、瞳孔較大 | 色像差的差別較容易察覺 |
| 問哪側的字清楚 | 色覺異常者仍可比較 |
| 小瞳孔、年長者反應不明 | 不強求紅綠；保留先前 MPMVA 結果 |

兩色焦點差約 **0.44～0.50 D**；相同清晰度時，可視作中間黃光約 **570 nm** 聚焦在網膜。

> [!note] 無法調到完全相同時
> 課堂／部分國考題讓年輕人取「最少負度數、綠稍清楚」；可能略 over-minus，靠調節補回。年長者不宜照搬。兩眼判讀標準要一致，紅綠也不能取代先前球面檢查。
''')
r.set(4,'JCC 做完：回頭查球面有沒有偏掉','''
> [!big] 微調球面＝第二次 MPMVA，是 MSR 的最後確認。

調散光時雖有球面補償，病人反應與步距仍可能讓結果偏移，所以再確認一次。

::: flow
加＋1.00 DS 霧視，課堂約降至 20/50～20/60
逐次少一點正／多一點負，常以 0.25 D 為小步
讀得更多時繼續，已無進步則不要再加負
停在最好視力下，最正／最少負的球面
:::

「每 −0.25 D 多讀一行」是課堂觀察指引，並非每個人都剛好一行。若突然讀很多，回查是否跳過合適終點。
''')
r.set(5,'「更清楚」與「更小更黑」要分開','''
> [!big] 字更黑，不等於能分辨更多細節。

| 病人的回答 | 怎麼處理？ |
|---|---|
| 真能多讀字、分辨細節 | 可以支持小步調整 |
| 只是更小、更黑，視力沒進步 | 偏向保留較正／較少負的那片 |
| 已讀 20/20 | 仍確認是否能少用負鏡，不自動結束 |

**霧視是起點，不是終點**。最後仍看最佳視力與 MPMVA；一眼完整做完再換另一眼。

> [!warn] 課堂與考題的說法有差
> 老師不建議第二次 MPMVA 以紅綠當終點；107 生特 32 卻把紅綠列為終點選項之一。遇到此題保留出題脈絡，不能把任一說法改成唯一規則。結果衝突時也不能直接讓紅綠凌駕所有檢查。
''')
r.set(6,'試鏡架：更接近日常戴眼鏡','''
> [!big] 讓病人戴著架子看，你也看得到他怎麼看。

**Trial frame（試鏡架）**裝試片，配手持 JCC，叫 **refraction in free space（自由空間驗光）**。換片慢一些，但比較接近真正眼鏡。

::: cols b o
### 位置比較自然
較少大儀器在眼前的近感性刺激。
**內聚**是兩眼向鼻側轉；**調節**是眼內增加對焦力量，兩件事會互相牽動。
|||
### 可以看見病人的習慣
歪頭、轉頭、眨眼，或用旁邊視網膜看（偏心注視）。
低視力病人尤其需要觀察這些動作。
:::

適合低視力與偏鄉義診；配可攜式視力表也能完成自覺式驗光。
''')
r.set(7,'距離與傾斜：鏡片放在哪，也會影響效果','''
> [!big] 用接近日常眼鏡的位置，評估實際戴起來的感覺。

| 名詞 | 具體在哪？ | 為什麼要管？ |
|---|---|---|
| 頂點距離 Vertex distance | 鏡片後面到眼睛角膜的距離 | 高度數時，遠近改變有效力量 |
| 前傾角 Pantoscopic tilt | 鏡片下緣相對上緣靠近臉的傾斜 | 影響實際透鏡觀看條件 |

試鏡架戴好後較容易維持、評估這些條件；綜合驗光儀裡頭往前、歪頭，距離也可能變。試鏡架同樣需要調整，並非戴上就自動正確。

| 補充速記 | 要記的值 |
|---|---|
| 試鏡架兩眼軸度 | 檢查者看，皆逆時針增加 |
| 低視力 JCC | 可能選 ±1.00 D，非一律用 ±0.25 D |
''')

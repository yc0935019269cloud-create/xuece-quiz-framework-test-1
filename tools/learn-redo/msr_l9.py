from optometry_common import *
r=Rewrite('optom2-u2-msr','l9')
r.set(0,'鐘面圖：哪條線較黑，就從那條線找軸','''
> [!big] 先霧視，再問最黑的線；用負柱鏡把各線調成一樣黑。

**鐘面圖（astigmatic dial／clock dial）**像鐘面，線穿過中心。散光未矯正時，不同方向可能深淺不一。

| 步驟 | 操作 |
|---|---|
| 1 | 暫移除柱鏡 |
| 2 | 加正球鏡霧視到約 20/40，讓 COLC 在網膜前 |
| 3 | 問哪條線最黑，決定負柱鏡軸 |
| 4 | 加負柱鏡，直到線一樣黑 |

**負柱鏡軸＝最黑線的鐘點數×30°**，超過 180° 就減 180°。這是「鐘面線 → 矯正軸」的換算，不是說指針本身的角度就等於處方軸。
''')
r.set(1,'鐘點換軸位：先看同一條直線的兩端','''
> [!big] 12—6 點是直線；對應的負柱鏡軸卻是水平 180°。

| 最黑線鐘點 | 負柱鏡軸 | 最黑線鐘點 | 負柱鏡軸 |
|---|---|---|---|
| 1／7 | 30° | 4／10 | 120° |
| 2／8 | 60° | 5／11 | 150° |
| 3／9 | 90° | 6／12 | 180° |

兩條相鄰線同樣黑，取中間：**11、12 點 →11.5×30＝345° →165°**。跨過 12 點也要沿鐘面取中間：12、1 點 →負軸 15°。

若題目問**正柱鏡軸**，把負軸再轉 90°：2 點→負軸60°→正軸150°。

Clock dial 線組通常隔 30°；**Fan（扇形圖）**常隔 15°。兩者是自覺比較圖線、調柱鏡的方法，不需要再拿 JCC 翻片。
''')
r.set(2,'針孔與裂孔：小圓孔，和一條窄縫','''
> [!big] 針孔查「縮小模糊後能不能看好」；裂孔分方向測。

::: cols b o
### 針孔 Pinhole
只讓較中央的光通過，縮小模糊光斑，增加**焦深**（可容忍的前後失焦範圍）。
改善支持有可矯正的屈光因素；沒改善還需查眼病、原本已達最佳等可能。
|||
### 裂孔板 Stenopaic slit
只開一條窄縫；轉動後，分開測不同方向。
適合不規則散光（如圓錐角膜）或不易完成其他方法的病人。
:::

兩者都要病人看視標回答。**針孔沒改善不等於直接診斷眼病**，還要配合其他檢查。
''')
r.set(3,'裂孔板走一次：兩個方向合成一張處方','''
> [!big] 先測一條，再轉 90° 測另一條。

| 步驟 | 為什麼？ |
|---|---|
| 最佳球面 →霧視 | 先有可比較的起點，COLC 放在網膜前 |
| 旋轉窄縫，找最清楚方向 | 課堂霧視條件下，對應最正度數／負柱鏡軸 |
| 加球鏡到 MPMVA | 記這個方向需要的度數 |
| 縫轉 90°，再調到 MPMVA | 記另一方向度數 |
| 畫屈光十字，寫 S／C ×軸 | 兩方向差就是柱鏡 C |

35° 得＋2.50 D，125° 得 −1.00 D：差是 −3.50 D → **＋2.50／−3.50 ×35**。

針孔約 **1 mm**；裂孔縫寬 **0.5～1.0 mm**，2.5 mm 不是這裡的適當值。角膜主子午線不互相垂直，支持不規則散光，可考慮裂孔板。眼部受傷且兩眼矯正視力不等時，不宜硬做一般雙眼平衡。
''')
r.set(4,'順規、逆規：先問你看的是哪個角度','''
> [!big] 用負柱鏡處方軸分類，別拿角膜強經線直接套。

**TABO 軸度**：檢查者面對病人，從水平開始，兩眼刻度都逆時針增加；水平寫 180°，垂直90°。

| 負柱鏡軸在哪？ | 名稱 | 未矯正眼較強收光方向 |
|---|---|---|
| 近水平 | 順規 With-the-rule | 近垂直 |
| 近垂直 | 逆規 Against-the-rule | 近水平 |
| 斜向 | 斜散光 Oblique | 斜向 |

之所以反過來，是因負柱鏡在**軸的垂直方向**有完整負力量，用它減弱原本較強的方向。若題目給正柱鏡處方，先轉成負柱鏡再套表。
''')
r.set(5,'角度範圍：中心先記，邊界看題目定義','''
> [!big] 先抓 180° 順規、90° 逆規、45／135° 斜向。

| 類型 | 常見負柱鏡軸範圍 |
|---|---|
| 順規 | 約 150°～180°，跨到 1°～30° |
| 逆規 | 約 60°～120° |
| 斜散光 | 約 30°～60°、120°～150° |

課堂分類邊界有相鄰區間相接的寫法，像 30°、120° 本身，依老師／題目採用的定義，不把交界當成兩種都必然成立。

國考「120～150° 斜散光」要看清楚它給的是何種軸；**負柱鏡軸**與**角膜較強子午線**互相垂直。先確認定義，再判類別。
''')
r.set(6,'4 公尺驗光：視標仍需要一點看近的力量','''
> [!big] 未做距離補償的 4 m 結果，遠用球面再往負 0.25 D。

視標不是無限遠，距離 **4 m** 時，物方聚散度＝**−1/4＝−0.25 D**。若眼睛完全放鬆，這個有限距離會讓驗出的球面較正；要換成遠用，減回 0.25 D。

| 條件 | 怎麼處理？ |
|---|---|
| 課堂標準 6 m | 臨床常近似無限遠，並非數學上真的無限遠 |
| 4 m，結果尚未補償 | S 減 0.25 D；C、軸不變 |
| 儀器／流程已含距離補償 | 不能重複再減 |

病人若用調節補足有限距離需求，結果也可能受影響，所以驗光仍要控制調節，不能假設一定用了剛好 0.25 D。
''')
r.set(7,'兩種「加減 0.25」：先分原因','''
> [!big] 距離補償和放鬆調節，是不同用途。

| 情境 | 操作 | 原因 |
|---|---|---|
| 4 m 原始結果＋3.50／−1.00 ×90 | 遠用變＋3.25／−1.00 ×90 | 扣有限檢查距離 |
| 想暫時霧視 | 常加＋1.00～＋1.50 DS，視力約 0.3～0.5 | 讓眼睛放鬆，不是最終處方 |
| 多給負鏡（凹透鏡） | 可能刺激調節 | 病人可能用力把字看清楚 |

先看題目問「最終遠用處方」還是「檢查時暫加的鏡片」，別把霧視的正鏡留在最後處方裡。
''')
r.save()

from optometry_common import *
r=Rewrite('optom2-u3-vf','l3')
r.set(0,'掛布式：盯著布中央，看小點從哪裡出現','''
> [!big] 黑布是座標平面，主要測中央約30°。

**Tangent screen（掛布式／正切視野）**像牆上一張黑色靶布。病人眼睛固定看中央，檢查者在布面移動小視標，標出能看到的範圍。

| 特色 | 怎麼理解？ |
|---|---|
| 中央約30° | 不拿它測最遠的周邊 |
| 比對坐精細 | 位置能記在布面座標上 |
| 使用情況 | 課堂說台灣較少使用，不代表此法無效 |

這裡「正切」描述用平面屏幕把視角投到平面，不是新的眼病名稱。
''',image=True)
r.set(1,'布上的圓與線：標的是視角','''
> [!big] 固定距離，布面位置才能換成角度。

| 構造／條件 | 課堂值 |
|---|---|
| 同心圓 | 以注視點為中心，每5°一圈 |
| 放射線 | 每15°一條 |
| 常見檢查距離 | 100 cm＝1 m |
| 改到2 m、布尺寸不變 | 同一布面涵蓋角度變小，偏重更中央範圍 |

所以換距離不能沿用錯誤刻度。中央30°的定位仍屬中心視野，國考不把掛布式歸周邊檢查。
''')
r.set(2,'弧形視野計：把測量面彎到眼前','''
> [!big] 弧臂能轉方向，用來查周邊範圍。

**Arc perimetry（弧形視野）**把視標放在弧形臂板上。眼睛固定在中心附近的指定位置，再沿弧移動視標；旋轉弧臂就能換另一條方向測。

| 形式 | 共同工作 |
|---|---|
| 固定式、手持式、半弧型 | 讓視標沿不同視角移動，查周邊能否察覺 |

此類工具19世紀（1800年代）已出現；課堂提到台灣較會使用。重點先記外形與測周邊的工作。
''',image=True)
r.set(3,'平面布與弧臂：不要只背兩個名字','''
> [!big] 布查中央；弧臂能把目標帶到更周邊。

| 比較 | 掛布式 Tangent screen | 弧形 Arc |
|---|---|---|
| 表面 | 平面的黑布 | 彎曲臂板 |
| 主要範圍 | 中央約30° | 可測周邊 |
| 換方向 | 在布上不同位置移動 | 弧臂轉到不同子午線 |
| 課堂台灣使用描述 | 較少 | 較常見 |

題目問「哪個不是周邊視野檢查」：在對坐、Goldmann、弧形、掛布式之中，選**掛布式**。
''')
r.set(4,'Goldmann：在標準化大碗裡找光點','''
> [!big] 固定背景與刺激條件，前後檢查才容易比較。

**Goldmann 碗狀視野計**有均勻照明的半球碗面，病人注視中央，檢查者控制光點的位置、大小與亮度。

| 部分 | 工作 |
|---|---|
| 半球碗面 | 以較標準的背景測不同視角 |
| 光點視標 | 可用不同大小、亮度 |
| 觀察管 | 檢查者監看病人有沒有離開注視點 |

比非標準化掛布測量更容易重複與追蹤；仍依賴操作、注視與病人反應，不是同名儀器就保證每次相同。
''',image=True)
r.set(5,'I4e、V4e：先看大小，再看亮度','''
> [!big] 同一規格的光點，沿不同方向找「剛看見」的位置。

| 視標記號 | 代表什麼？ |
|---|---|
| 羅馬數字0～V | 視標大小，例如I、V；V較大 |
| 後面的數字＋字母 | 亮度等級，例如4e |

**動態**：固定規格的光點從看不到處移入，連起首次看到的位置，得到一圈 **isopter（等視力線）**。

**靜態**：位置固定，改亮度／視標條件，找剛好看見的閾值。Goldmann兩種都能做，主要以動態使用，不能說只能動態。
''')
r.set(6,'一圈圈線：每圈都要連著視標規格讀','''
> [!big] 大亮視標圈在外，小暗視標圈在內。

同一眼看同一個固定注視點：**小暗光**通常要更靠中央才察覺；**大亮光**在周邊就可能看見。

| 圖上看到 | 該怎麼讀？ |
|---|---|
| 多圈線 | 不同視標規格的 isopter |
| 外圈大 | 先看用了多大多亮的視標，不能直接說功能比內圈好 |
| 顳側小盲區 | 對應視神經盤的生理盲點 |

課堂有43歲正常人右眼示例。追蹤前後變化，要在相近條件與相同規格下比較。
''',image=True)
r.set(7,'青光眼為何常畫出弧形？','''
> [!big] 缺損跟著受傷的神經纖維路徑走。

**RNFL＝retinal nerve fiber layer，視網膜神經纖維層。** 感光後的訊號沿神經纖維匯到視神經盤。

| 結構 | 連到視野形狀 |
|---|---|
| 纖維繞過黃斑、彎向視神經盤 | 傷到一束時，可出現弧形缺損 |
| 上下以水平縫為重要分界 | 常出現水平中線兩側不對稱，例如鼻側階梯 |

這不是說所有青光眼缺損都只有一條弧。

**Octopus 900** 是可自動化做動態視野的工具，也能沿用 Goldmann 式的檢查概念；Goldmann 傳統上由檢查者半手動控制。
''')
r.save()

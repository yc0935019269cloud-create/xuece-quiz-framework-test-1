from optometry_common import *
r=Rewrite('optom2-u3-vf','l1')
r.set(0,'視力與視野：清楚度，和看得到的範圍','''
> [!big] 能讀 1.0，不代表四周都看得到。

請眼睛固定看前方同一個點。你還能察覺左、右、上、下的物體；這整個範圍就是**視野（visual field，VF）**。

::: cols b o
### 視力表
測中央分辨小字的能力。
問「看得清不清楚？」
|||
### 視野檢查
測不同位置還能不能察覺目標。
問「哪裡看得到？需要多亮才看到？」
:::

用來**診斷與追蹤**疾病。有些青光眼患者中央視力仍好，周邊已少了一塊。
''')
r.set(1,'從眼睛到腦：任何一段受損，都可能少一塊','''
> [!big] 看缺損的位置與形狀，幫忙找受損在哪段。

| 位置／疾病 | 白話連結 |
|---|---|
| 視網膜 | 眼底接光層；剝離、裂孔等會影響相應區域 |
| 黃斑部 | 網膜中央精細看東西的區域；病變可影響中心 |
| 視神經 | 把影像訊號送出眼睛；青光眼、缺血性病變可破壞它 |
| 腦內視覺路徑 | 後續傳訊線路；腫瘤、外傷、中風可造成特定缺損 |

**中心盲區**＝注視附近有看不到的區域。**缺血**＝血流供氧不足。

對坐視野先快篩大缺損；自動視野計能更細地測敏感度，並比較前後變化。缺損型態是定位線索，不能單靠一張圖診斷。
''')
r.set(2,'兩種測法：原地變亮，或從外往內走','''
> [!big] 靜態測某一點要多亮；動態找看得到的邊界。

| 方法 | 同一個小光點怎麼變？ | 測到什麼？ |
|---|---|---|
| {b:靜態 Static} | 位置固定，逐次改亮度；部分方法也改大小 | 該點的敏感度／閾值 |
| {o:動態 Kinetic} | 大小與亮度固定，從看不到處移入 | 首次看到的位置，連成邊界 |

**閾值（threshold）**＝剛好能察覺目標的強度；越微弱的光也看得到，敏感度越高。

眼睛要一直盯中央，不追著光跑；否則測到的是轉眼後的新範圍。
''')
r.set(3,'八種工具：先分「快篩、畫邊界、測每點」','''
> [!big] 名字很多，先用工作方式分組。

| 工作／特色 | 工具 |
|---|---|
| 面對面快篩 | 對坐視野 Confrontation |
| 在平面布上找位置 | 掛布式 Tangent screen／正切視野 |
| 沿弧面測周邊 | 弧形 Arc perimetry |
| 標準化碗面、畫等視力線 | Goldmann；動態為主，也可靜態 |
| 電腦逐點測亮度閾值 | SAP，例如 Humphrey、Medmont |
| 閃爍條紋篩檢 | FDT 雙倍頻視野 |
| 頭戴裝置 | VR 視野 |
| 對準眼底位置測 | Microperimetry 微視野 |

掛布式通常測**中央約30°**，考題不把它歸為周邊視野檢查。周邊可用對坐、弧形或 Goldmann。動態移太快會因反應時間漏掉邊界。
''')
r.set(4,'方向以病人為準：鼻側靠鼻，顳側靠耳','''
> [!big] 看右眼：右方是顳側；看左眼：左方是顳側。

固定看中央點，用上下與左右兩條線切成四格，就是**四個象限**：鼻上、鼻下、顳上、顳下。

| 單眼正常範圍，課堂約值 | 哪側較寬？ |
|---|---|
| 上60°、鼻60° | 較受眉骨、鼻子等外形限制 |
| 下75° | 比上方寬 |
| 顳110° | 最寬，朝耳朵那側 |

這裡的 ° 是離注視點的視角，不是視力 1.0，也不是鏡片度數。範圍受視標、檢查方法與個體影響。
''',image=True)
r.set(5,'正常也有盲點：視神經出口沒有感光細胞','''
> [!big] 網膜的鼻側出口，對應到視野顳側盲點。

**視神經盤**是神經離開眼球的出口，這裡沒有感光細胞。因此每眼正常視野都有一小區看不到，叫**生理盲點**。

| 位置／規則 | 怎麼記？ |
|---|---|
| 盲點位置 | 注視點外側約15°，稍低於水平線 |
| 右眼 | 病人看出去偏右 |
| 左眼 | 病人看出去偏左 |
| 「尊重中線」 | 缺損常沿這條線停住，不隨意跨越 |

腦內路徑病灶常沿**垂直中線**；青光眼神經纖維缺損常沿**水平中線**。這是常見型態，仍要配合完整檢查定位。
''')
r.set(6,'視野山丘：高度是敏感度，不是眼睛長出山','''
> [!big] 中央能看很微弱的光，畫得高；周邊需要較亮，畫得低。

把「每個位置有多敏感」畫成高度，就是 **Hill of vision（視野山丘）**。

| 山的哪裡 | 對應視覺功能 |
|---|---|
| 山頂 | 注視點／中央小凹附近最敏感 |
| 往外山坡 | 越周邊，敏感度通常越低 |
| 小洞 | 生理盲點 |

**Isopter（等視力線）**像等高線：把同一規格視標「剛好看得到」的位置連起來。這裡講的相同敏感度，不是視力表都讀到同一行。
''',image=True)
r.set(7,'同一雙眼：視標換大換亮，邊界會變大','''
> [!big] 視野圖的圈變大，先看是否只是視標更容易看見。

::: cols b o
### 小、暗的光點
比較難察覺，通常靠中央才看到。
畫出的 **isopter 靠內**。
|||
### 大、亮的光點
比較容易察覺，周邊就可能看到。
畫出的 **isopter 靠外**。
:::

動態視野把這些邊界一圈圈畫出來；靜態視野則固定位置，測「這點多微弱也能看見」。

報告敏感度常用 **dB（分貝）**：視野計用它表示光相對儀器最亮刺激被減弱多少，不是聲音，也不是焦耳。能看到減弱更多的光，dB 就較高。
''')
r.save()

r.intro=dict(type='intro',title='稜鏡、偏心、瞳距：先認每個量的意思',body=['> [!big] 同一片鏡片，看過的位置不同，也可能多出稜鏡效果。','','本課依序複習稜鏡度Δ、Prentice法則、兩眼瞳距與光心錯位，以及焦度計能測什麼。D、Δ、mm先分開，再算。'])
r.set(0,'1Δ：一公尺外，光線偏一公分','''
> [!big] Δ看「偏了多少」，D看「鏡片聚散光有多強」。

稜鏡有厚邊**base（基底）**、相對薄尖**apex（頂端）**。光線偏向基底，眼睛回推看到的物體位置則朝頂端。

| 量 | 單位／算式 |
|---|---|
| 稜鏡量P | Δ＝偏移cm÷距離m |
| 已知Δ、距離，求偏移 | 偏移cm＝Δ×距離m |
| 已知Δ、偏移，求距離 | 距離m＝偏移cm÷Δ |

例：400 cm先換4 m，偏30 cm →30÷4＝**7.5Δ**。50 mm先換5 cm，0.5Δ造成5 cm偏移→距離＝5÷0.5＝**10 m**。

單位先換好：mm÷10→cm，cm÷100→m。兩眼合成怎麼算，下頁用方向分清楚。
''',extra=[page('兩眼相加前：BU、BD、BI、BO是相對每隻眼的命名','''
> [!big] 「同向相加」要先說清是基底朝哪裡，不只看文字。

| 名稱 | 基底在哪？ |
|---|---|
| BU／BD | 向上／向下 |
| BI／BO | 向鼻側／向耳側 |

要算**兩眼相對分離量**時：

| 配置 | 相對效果 |
|---|---|
| 右2ΔBU、左3ΔBD | 垂直反向，合計5Δ；相對哪眼的方向依題目 |
| 兩眼都BU，例如2與3 | 一起上偏的部分抵消，垂直差1Δ |
| 兩眼都BO，或都BI | 左右眼的物理基底朝相反左右，水平相對量相加 |
| 一眼BO、另一眼BI | 兩眼物理上可能朝同一側，水平相對量取差 |

不要把「都BO」誤讀成兩眼基底都向病人的右方。
''')])
r.set(1,'稜鏡換算：先寫要找偏移還是距離','''
> [!big] 一條關係可反算三個量，不用多背三句口訣。

| 已知 | 要找 | 計算 |
|---|---|---|
| 距4 m、偏30 cm | P | 30÷4＝7.5Δ |
| 12Δ、偏80 cm | 距離 | 80÷12≈6.67 m |
| 0.5Δ、偏50 mm | 距離 | 50 mm＝5 cm；5÷0.5＝10 m |

先把題目數字標上cm、m、Δ，再代入。方向則另外判：**光線往基底，影像往頂端**；不要拿數字大小猜BU、BD。
''')
r.set(2,'Prentice：離開光學中心，也會看到稜鏡效果','''
> [!big] 偏得越遠、鏡片越強，稜鏡效果越大。

**OC＝optical center，光學中心**。視線沒穿過光心時，可把當地效果想成鏡片力量加上一點稜鏡。

| 符號 | 指的是什麼？ |
|---|---|
| c | 視線位置到OC的偏心距離，先換cm |
| F | 該方向鏡片力量，D；算大小用絕對值 |
| P＝c×|F| | 稜鏡大小，Δ；基底方向另判 |

| 鏡片 | 觀察位置的基底方向 |
|---|---|
| 正鏡：像兩稜鏡底對底 | 朝光心 |
| 負鏡：像兩稜鏡尖對尖 | 背離光心 |

例：正3 D，視線在OC下8 mm →0.8×3＝**2.4ΔBU**，因光心在上。球柱鏡要用偏心方向的力量；軸180°：水平S、垂直S＋C；軸90°則相反。這個簡表限主方向沿水平／垂直的情境。
''')
r.set(3,'PD與DBOC：眼睛位置，和鏡片光心位置','''
> [!big] 對稱配置才用差÷2；不對稱就每眼各算。

**PD（pupillary distance）瞳距**：兩眼瞳孔中心距離。**DBOC**：兩鏡片光心距離。

| 例：PD60、DBOC66 mm，左右對稱 | 每眼 |
|---|---|
| 光心總共比瞳孔寬6 mm | 各偏3 mm＝0.3 cm |
| 正5.00 D | 0.3×5＝1.5Δ，基底朝外側光心→BO |
| 兩眼相對合計 | 3.0ΔBO |

正鏡DBOC>PD→BO、<PD→BI；負鏡反過來。若單眼PD或裝配不對稱，不能硬把總差除2。
''',extra=[page('看近往下看：兩眼同向移動，垂直量通常看差','''
> [!big] 同號鏡片往下看，基底通常同向；兩眼不平衡看差值。

| 同樣往下偏心 | 兩眼垂直不平衡 |
|---|---|
| 兩眼都正或都負 | 先每眼c×|F|，同向部分取差 |
| 一正一負 | 基底反向，大小相加 |

水平往鼻側看時，若兩眼同為正或同為負，BI／BO相對作用常相加；仍先畫每眼光心、視線與基底方向。

近看兩眼內聚，近PD較小。課堂近似：**近PD＝遠PD×距離/(距離＋27 mm)**，所有長度同單位。遠PD65 mm、閱讀400 mm →65×400/427≈**61 mm**；距離越遠越接近遠PD。
''')])
r.set(4,'焦度計：量鏡片整體效果，不是直接量每個表面','''
> [!big] 後表面靠托，量後頂點；翻到前表面靠托，量前頂點。

**Lensometer／focimeter＝焦度計、驗度儀**；量鏡片的度數、散光軸、稜鏡與光心位置。

| 測什麼？ | 操作／意義 |
|---|---|
| 單焦遠用度數 | 後表面靠托，讀後頂點屈光力 |
| 多焦ADD加入度 | 課堂用前頂點法：近區前頂點−遠區前頂點，同基準相減 |
| 視標偏離十字中心 | 該測點有稜鏡；課堂刻度1圈＝1Δ，依機型確認 |
| 想分開前、後表面屈光力或材料折射率 | 一般焦度計不能直接測得 |

例：遠區前頂點＋1.00、近區＋3.25 D →ADD＝**＋2.25 D**。**後頂點屈光力不等於後表面屈光力**。

散光對焦依課堂視標記法「短軸對較正、長軸對較負」；球鏡長短線同時清楚。視標上偏2圈→課堂讀2ΔBU；讀刻度前確認儀器標法。
''')

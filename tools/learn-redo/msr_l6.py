from optometry_common import *
r=Rewrite('optom2-u2-msr','l6')
r.set(0,'c：力量先保留，把方向轉準','''
> [!big] 跨軸比較；負柱鏡的軸追較清楚那面的紅點。

**跨軸（straddle）**：JCC 的兩條點線，分別在目前柱鏡軸的左右各 45°。儀器的 **A（axis）**標記對柱鏡軸；手持 JCC 的柄通常沿著這條軸。

| 動作 | 例如目前柱鏡軸 90° |
|---|---|
| 擺 JCC | 點線在 45°、135° |
| 翻給病人比 | 記較清楚那面，紅點在哪側 |
| 調柱鏡軸 | 往那個紅點方向轉，不一次轉到紅點位置 |
| 再比 | 直到翻面清楚程度相同 |

課堂粗軸起步可用 **15° →10° →5°…** 包夾；散光約1.00 D以上，軸差10°就可能明顯影響視力，改用更小步距，不一律從15°開始。
''')
r.set(1,'同一個例子：35° →20° →30° →25°','''
> [!big] 反應換邊，表示轉過頭；下一步縮小。

角度方向都以**檢查者面對病人**為準：逆時針增加，順時針減少。

| 目前軸 | 較清楚面的紅點在… | 改幾度？ | 新軸 |
|---|---|---|---|
| 35° | 順時針側 | −15° | 20° |
| 20° | 逆時針側，反向了 | ＋10° | 30° |
| 30° | 順時針側，又反向 | −5° | 25° |

繼續縮小，直到兩面一樣。**度數越高，角度步距越小**；例如 −2.75 DC 可從 5° →3° →1°。

軸是循環的：180° 和 0° 同方向；從 180° 往增加 10°，記 **10°**。不要只用數字大小判斷跨越邊界的轉法。
''')
r.set(2,'d：在精確軸上，再問柱鏡多不多','''
> [!big] c 改方向；d 固定方向、改力量。

| 步驟 d | 負柱鏡儀器 |
|---|---|
| 擺法 | **點對精確軸**，不跨軸 |
| 比較 | 紅點對軸較清楚 → 更多負柱鏡；白點 → 更少 |
| 終點 | 用步驟 b 的相同／拒絕與包夾法確認 |
| 配套 | 每 C 多 −0.50 D，S 補＋0.25 D |

有些儀器是**正柱鏡**：找軸追白點；找度數時，白點對軸較清楚表示想加正柱鏡。球面補償仍用 **ΔS＝−ΔC/2**。
''')
r.set(3,'四步擺位，放在一張表記','''
> [!big] 只有 c 跨軸；a、b、d 都點對軸。

| 步驟 | 找什麼？ | JCC 擺法 |
|---|---|---|
| a | 粗略方向 | 點對軸，試四個方向 |
| b | 粗略度數 | 點對粗略軸 |
| c | 精確方向 | **跨軸**，兩點線各偏 45° |
| d | 精確度數 | 點對精確軸 |

例如 d 的處方軸＝70°，兩條 JCC 點線在 **70° 和 160°**；若做 c，則在 25° 和 115°。

先確認儀器是負散或正散。正散例：＋2.00／＋1.25 ×80，兩輪都接受多＋0.25 C → 新 C＋1.75，S 減 0.25 → **＋1.75／＋1.75 ×80**。
''')
r.set(4,'有檢影：省的是搜尋，不是最後確認','''
> [!big] 已知方向與度數，直接從需要修的地方開始。

| 起始資料 | 課堂接續步驟 |
|---|---|
| 檢影找到散光，視力仍較差 | b →c →d |
| 已有散光，初始球面後 ≥20/25（0.8） | c →d |
| 檢影沒散光，調球面後 <20/20（1.0） | a 開始，重新搜尋 |

例如檢影 −1.00／−2.75 ×170，調球面後 20/25：直接 **c、d**；散光較高，找軸從 **5°** 小步開始。

整段仍一次只測一眼。遮蓋非受測眼，但請病人自然睜眼，不用力閉眼。
''')
r.set(5,'最後檢查：改很多時，回頭確認前一步','''
> [!big] 新度數若和起點差很大，軸位也可能需要重查。

| 看見這個條件 | 別漏掉的動作 |
|---|---|
| JCC 新 C 與初始值差約 1.00 D | 軸與度數都再確認 |
| 中高度散光 | 小角度修軸，避免來回跳過答案 |
| 電腦驗光散光 ≤0.50 D 的特定國考題 | 題目容許省略找軸；勿擴大成所有病人都免查 |

**一般順序仍是先軸、再度數**。完成一眼 MSR 才換另一眼；檢影通常讓兩眼打開，和 MSR 的遮蓋比較條件不同。
''')
r.save()

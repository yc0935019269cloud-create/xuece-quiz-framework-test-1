from optometry_common import *
r=Rewrite('optom2-u3-vf','l8')
r.set(0,'可靠度：這次測量過程穩不穩？','''
> [!big] 可靠度是檢查表現，和眼睛病多重是不同問題。

| 名詞 | 想像儀器在查什麼？ |
|---|---|
| Fixation losses／固視（注視）遺失 | 說好看中央，眼睛有沒有偏開？ |
| False positive／偽陽性 | 沒呈現該刺激卻按了嗎？ |
| False negative／偽陰性 | 前面能看見的位置，給更亮卻沒反應嗎？ |

高偽陽性可能讓圖**假裝很好**；高偽陰性可因疲勞，也可能是本來受損處反應不穩。別把不可靠簡化成「病人不認真」。
''')
r.set(1,'三個比例：百分比後面要知道測的是什麼','''
> [!big] 比例太高要查原因，不只看一個紅色警示。

| 指標 | 常見測法／偏高原因 |
|---|---|
| 固視遺失 | 在生理盲點出光還按；可能眼位移動，也可能盲點定位不準 |
| 偽陽性 | 太早／無適當刺激就按，依策略有不同估法 |
| 偽陰性 | 應較易看到的亮光漏按；疲勞或嚴重視野病變 |

| 門檻的來源 | 要怎麼記？ |
|---|---|
| 課堂與舊國考 | 固視20%、偽陽20%、偽陰33% |
| 其他常見資料 | 偽陽可用15%或舊策略33%；不可混成一個通用標準 |

偽陽10%不等於自動不可靠。**MD是功能整體指標，不是可靠度**。實際仍看儀器策略、眼動監看與整張結果。
''')
r.set(2,'MD、PSD、VFI、GHT：四個數字各管一件事','''
> [!big] MD看整體高度，PSD看凹凸，VFI看功能指數，GHT比上下。

| 縮寫／名稱 | 白話問題 |
|---|---|
| MD，Mean deviation 平均偏差 | 跟同齡常模比，整個山丘平均低多少？ |
| PSD，Pattern standard deviation 模式標準差 | 扣掉整體高低後，是否有局部凹洞？ |
| VFI，Visual field index 視野指數 | 用0～100%表示功能，中央權重較高 |
| GHT，Glaucoma hemifield test 青光眼半視野檢查 | 水平線上下對應區，是否不對稱？ |

VFI較少受白內障影響，並非完全不受影響，也不等於精確剩下多少視神經細胞。
''')
r.set(3,'同樣 MD 變差，PSD能提示形狀差異','''
> [!big] 一起下降像山變低；局部下降像山上挖洞。

| MD | PSD | 常見可能 |
|---|---|---|
| 明顯更負 | 正常附近 | 普遍下降，如白內障、小瞳孔、屈光未矯正 |
| 更負 | 升高 | 局部缺損，如青光眼／網膜疾病 |
| 近正常 | 升高 | 小範圍局部缺損，平均還沒明顯變 |

**MD −10比−2更低**，不是看負號後面數字小就比較好。PSD高常提示局部不規則；晚期若幾乎全面很差，PSD反而可下降，不能當嚴重度直線尺。

GHT會給超出正常、臨界、整體降低等結果；與圖形和其他指標一起讀。
''')
r.set(4,'追蹤：一次低分，先查是不是測量差','''
> [!big] 新缺損要重測，反覆一致才更可信。

| 情境 | 下一步 |
|---|---|
| 第一次做，不熟按鈕 | 教會、練習，必要時重測，考慮學習效應 |
| 新出現局部缺損 | 查看可靠度與遮擋，重測確認 |
| 多次同區下降 | 比較位置、深度、擴大與整體趨勢 |

**進展（progression）**是隨時間惡化；「PD模式偏差圖」本身不是時間趨勢。需要多次相同條件的結果，才知道是否真的持續變差。
''')
r.set(5,'GPA：在多次報告中找重複惡化','''
> [!big] 固定測法，再比時間；別拿不同點位硬連線。

**GPA＝Guided Progression Analysis，進展分析**。把基準和後續結果比，標出反覆惡化的位置，也可看MD／VFI隨時間的趨勢。

| 要固定 | 例子 |
|---|---|
| 範圍與策略 | 24-2對24-2，相同閾值策略 |
| 觀看條件 | 合適近用矯正、瞳孔條件相近、鏡片不擋 |
| 指導與反應品質 | 注視、按鈕規則、疲勞處理 |

課堂補充用 **MD每年下降超過約1 dB** 提醒較快進展；這是參考，不是單次下降1 dB就確定快速惡化。要看多次斜率、變異與病況。
''')
r.save()

from optometry_common import *
r=Rewrite('optom2-u4-bb','l3')
r.set(0,'稜鏡：光偏向基底，看到的影像移向頂角','''
> [!big] BU那眼看下行；BD那眼看上行。

**稜鏡（prism）**像有厚邊、薄尖的楔形鏡片。厚邊叫**基底 base**，相反的尖端叫**頂角 apex**。

| 先分兩件事 | 方向 |
|---|---|
| 光線經過稜鏡的偏折 | 朝基底 |
| 病人回推看到物體的位置 | 朝頂角 |

**BU＝Base Up，基底朝上，尖端朝下 →影像在下。**
**BD＝Base Down，基底朝下，尖端朝上 →影像在上。**

在兩眼放相反稜鏡，同一行字就分成上、下兩行，才可同時比較兩眼。
''')
r.set(1,'先確認哪行是哪眼，不靠背右上左下','''
> [!big] 哪眼放BU，哪眼就是下行；左右可以互換。

| 本課設定 | 該眼看到 |
|---|---|
| 右眼OD：3Δ BU | 下行 |
| 左眼OS：3Δ BD | 上行 |

**Δ是稜鏡度**，不是球鏡D，也不是軸位°。等量相反各3Δ，兩影像相對分離量約6Δ。

放好先短暫遮一眼，問留下的是哪行，再打開一起比；這是**確認對應**，不是整段都輪流遮著測。

例：上行較清楚→看上行的是左眼→**左S加＋0.25 D**。不能不看稜鏡配置，就認定上行永遠左眼。
''')
r.set(2,'Risley旋轉稜鏡：兩片力量相加或抵消','''
> [!big] 兩片相對角度改「量」，整組一起轉改「方向」。

**Risley prism**是綜合驗光儀裡的旋轉稜鏡組，由兩片稜鏡組合。

| 怎麼轉？ | 改什麼？ |
|---|---|
| 兩片相對反向互轉 | 合成稜鏡量改變；相反等量時可抵消為0 |
| 整組同向旋轉 | 合成基底方向改變 |

| 方向縮寫 | 意思 |
|---|---|
| BU／BD | 基底上／下，作垂直分離 |
| BI／BO | Base In／Out，基底鼻側／耳側，水平稜鏡 |

不要把「鏡片轉了」一律理解成稜鏡量增加；要看兩片是相對轉還是整組轉。
''')
r.set(3,'旋轉稜鏡的零刻度，照課堂機型讀','''
> [!big] 零刻度擺向，是辨認可調基底方向的提示。

| 課堂儀器刻度設定 | 調整後可產生 |
|---|---|
| 零刻度在水平 | 垂直BU／BD，用來上下分離 |
| 零刻度在90° | 水平BI／BO |

反向互轉到0時，兩片可處在等量相反（例如一片BI、一片BO），所以**淨量0**，不是兩片本身消失。

這些是課堂所用旋轉稜鏡的刻度讀法；換機型先看標記與說明。綜合驗光儀內建Risley與JCC，讓調整更方便。
''')
r.set(4,'垂直分離法：先霧視，再放稜鏡','''
> [!big] 每次只調較清楚那行所屬眼的球面。

| 順序 | 操作 |
|---|---|
| 1 | 選20/40視標，雙眼各＋0.75 D霧視 |
| 2 | 請閉眼，放一眼3Δ BU、另眼3Δ BD |
| 3 | 睜眼，短暫遮一眼確認上／下行對應 |
| 4 | 兩眼同看，問哪行清楚；那眼S加＋0.25 D |
| 5 | 重複比較，直到兩行最接近一樣 |
| 6 | 請閉眼，移除稜鏡，避免突發複視不適 |
| 7 | 睜眼，雙眼等量去霧，找MPMVA |

兩眼球面差值在去霧時保留；柱鏡與軸先不動。
''')
r.set(5,'一開始就一樣：用小改變確認能分辨','''
> [!big] 驗證病人真的有比較，不是一直回答「都可以」。

| 情況 | 課堂確認方式 |
|---|---|
| 一開始就說一樣 | 暫在一眼加−0.25 D，問該行有沒有變清楚，之後回到應比較的設定 |
| 終點不明 | 小步調過頭再退回，用bracketing包夾 |
| 要放／拿稜鏡 | 先請閉眼，避免畫面突然跳動 |

用小改變查反應是**暫時確認**，不代表一般平衡規則改成「糊眼一直加負」。主要比較仍是**清楚那眼加正**。

此法兩眼同時看兩行；不要和連續交替遮蓋混淆。
''')
r.set(6,'方便同時比，但沒有融像鎖','''
> [!big] 不用記上一行，是優點；影像分離，是限制。

::: cols b o
### 適合的比較條件
兩眼最佳視力接近、能同時看到兩行。
不需記住上一片影像，短期記憶較弱也較容易比較。
|||
### 主要限制
需要旋轉稜鏡；兩眼影像分離，缺乏融像，可能增加平衡變異。
課堂稱常用但較不準，不是對所有情境的絕對排名。
:::

遠視、眼球震顫等依課堂選法須慎用；最佳視力不等時不硬比兩行清楚度，改評估紅綠等方法。
''')
r.set(7,'普通兩行字，和兩組紅綠，是兩種比較','''
> [!big] 沒有紅綠反應，限制的是紅綠版本，不是所有稜鏡分離。

| 版本 | 病人回答 |
|---|---|
| 垂直稜鏡分離模糊比較 | 上行或下行哪個清楚？ |
| 稜鏡分離紅綠 | 每行內，紅底或綠底的字哪個清楚？ |

舊教材把「紅綠沒有反應」直接列在普通垂直分離法禁忌，容易混淆，這裡分開記。紅綠版本仍需能穩定回答。

兩個版本都不靠偏光濾片分左右眼；**偏光法是另一套工具**。課堂對遠視與震顫的限制，則要從調節控制、分離是否加重不穩來考慮。
''')
r.save()

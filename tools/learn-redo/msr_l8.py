from optometry_common import *
r=Rewrite('optom2-u2-msr','l8')
r.set(0,'正散、負散：同一副鏡片的兩種寫法','''
> [!big] 換寫法，不換鏡片效果。

處方 **S／C ×軸**：S 是球鏡；C 是柱鏡；軸是柱鏡不加力量的方向。垂直軸的方向多加完整 C。

把「哪個方向當基準」換掉，就是**處方轉換（transposition）**：

| 步驟 | 新寫法 |
|---|---|
| 1．另一方向當 S | 新 S＝舊 S＋舊 C |
| 2．反向補差距 | 新 C＝−舊 C |
| 3．換到垂直方向 | 新軸＝舊軸 ±90° |

軸≤90° 就加 90°，>90° 就減 90°；結果放在 **1～180°**。
''')
r.set(1,'算一次，再用兩方向驗證','''
> [!big] −2.00／−1.50 ×180＝−3.50／＋1.50 ×90。

| 原處方 | 換寫法 |
|---|---|
| −2.00／−1.50 ×180 | S＝−3.50；C＝＋1.50；軸＝90° |
| ＋1.00／−2.00 ×90 | −1.00／＋2.00 ×180 |
| −3.00／−1.50 ×15 | −4.50／＋1.50 ×105 |

第一組驗算：原本水平 −2.00、垂直 −3.50；新寫法垂直 S＝−3.50，水平 S＋C＝−2.00。**每個方向力量都一樣**。

0° 和 180° 同一條線，處方寫 180°。不要把轉換誤當成只換 C 的正負。
''')
r.set(2,'主子午線：把處方攤成兩條力量','''
> [!big] 軸上＝S；垂直軸＝S＋C。

**主子午線**就是力量最大、最小的兩個方向；規則散光兩方向差 90°。

例如 **＋1.00／−2.00 ×90**：

| 方向 | 算法 | 鏡片力量 |
|---|---|---|
| 90°（軸方向） | S | ＋1.00 D |
| 180°（垂直軸） | S＋C | −1.00 D |

先畫這兩條，才判斷散光類型；不能只看到球鏡＋1.00 就說兩方向都遠視。
''')
r.set(3,'處方的正負，是在描述需要哪種矯正','''
> [!big] 需要負鏡＝原眼該方向偏近視；需要正鏡＝偏遠視。

在放鬆調節、看遠的分類情境：

| 需要的矯正度數 | 原眼該方向的焦線位置 |
|---|---|
| 負 | 網膜前，收光過強 |
| 正 | 網膜後，收光不足 |
| 0 | 網膜上 |

這是在判**未矯正眼睛**，不是說「放上負鏡片，光一定聚在網膜前」。負鏡正是用來把偏前的焦點往後移。

兩方向平均＝**SE＝S＋C/2**；力量差大小＝**|C| D（散光／Sturm 間距）**，不要把 D 的差誤當毫米距離。
''')
r.set(4,'五類散光：先算兩方向，再看符號','''
> [!big] 一個 0 叫單純；同號叫複合；異號叫混合。

| 算出的兩條主子午線矯正度數 | 分類方法 |
|---|---|
| 0 和負 | 單純近視散光 |
| 負和負 | 複合近視散光 |
| 0 和正 | 單純遠視散光 |
| 正和正 | 複合遠視散光 |
| 正和負 | 混合散光 |

例 **＋1.00／−2.00 ×90** → 兩方向＋1.00、−1.00 → **混合散光**。轉成正柱鏡寫法，分類也不會變。
''')
r.set(5,'把五個名字連回眼內的前後位置','''
> [!big] 近視焦線在前；遠視在後；0 就在網膜。

| 類型 | 未矯正時兩條焦線 |
|---|---|
| 單純近視 | 一前、一在網膜 |
| 複合近視 | 兩條都在前 |
| 單純遠視 | 一後、一在網膜 |
| 複合遠視 | 兩條都在後 |
| 混合 | 一前、一後 |

**最小錯亂圓 COLC** 在兩焦線的屈光度中點；先放到網膜適當位置，再藉柱鏡縮小兩方向差距。

另有一套**方向分類**，別混淆：負柱鏡軸近水平是順規、近垂直是逆規、斜向是斜散光（如 120～150° 題型）。前面五類看正負，這三類看角度。
''')
r.save()

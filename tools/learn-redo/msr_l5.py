from optometry_common import *
r=Rewrite('optom2-u2-msr','l5')
r.set(0,'a：先找散光大概在哪個方向','''
> [!big] 還不知道軸位，先試四個方向。

前面已調好球面，但視力仍不到 **20/20（1.0）**，或檢影沒找到散光，就從這步開始。

| 順序 | 在做什麼？ |
|---|---|
| 1 | 測右眼 OD 時遮左眼 OS；讓兩眼自然睜開 |
| 2 | 課堂做法先調入 −0.25 DC，當作很小的試探柱鏡 |
| 3 | JCC **點對軸**：紅點或白點的連線對上目前試的柱鏡軸 |
| 4 | 翻轉同一片 JCC，問哪次較清楚 |
| 5 | 依次試 180°、90°、45°、135° |

**DC 是柱鏡度數**；「接受」是指病人比較後支持保留／增加這個方向的負柱鏡，不是病人說出角度。
''')
r.set(1,'四條線不是八個不同方向','''
> [!big] 一條軸線有兩端；轉 180°，仍是同一條線。

| 處方軸位 | 同一條線兩端 |
|---|---|
| 180°（水平） | 0°—180° |
| 90°（垂直） | 90°—270° |
| 45°（斜） | 45°—225° |
| 135°（另一斜向） | 135°—315° |

處方用 **1～180°**，水平通常記 180°。

::: cols g p
### 相鄰兩方向都接受
45°、90° 都想要負柱鏡 → 粗略軸取中間 **67.5°（課堂約 67°）**，之後還會細修。
|||
### 四方向都不接受
支持沒有明顯、可測出的規則散光，停止這段找散光；視力差仍要查其他原因。
:::
''')
r.set(2,'病人選哪次，驗光師才翻譯成加或減','''
> [!big] 問「清楚嗎」，不要問病人「紅點嗎」。

以**負柱鏡儀器**為例，目前柱鏡軸固定，JCC 點對軸後翻面：

| 哪一種擺位較清楚？ | 代表想怎麼改 C？ |
|---|---|
| {r:紅點連線對準柱鏡軸}的那次 | 增加負柱鏡，例如 −1.00 → −1.25 D |
| 白點連線對準柱鏡軸的那次 | 減少負柱鏡，例如 −1.00 → −0.75 D |

病人看不到點的位置；你問「**1、2，哪個字比較清楚或較不扭曲？也可以說差不多。**」

課堂的終點確認還用到**第一次說一樣／加一次後又說一樣**，那是連續兩輪的反應，不是把選項 1 永遠當接受、選項 2 永遠當拒絕。
''')
r.set(3,'「一樣」怎麼處理：比較的是兩輪反應','''
> [!big] 第一次相同，還要用下一小步確認終點。

| 課堂判讀 | 下一步 |
|---|---|
| 紅點對軸較清楚 | 接受更多負柱鏡 |
| 第一次翻片說兩次一樣 | 暫按接受，再加一小步確認 |
| 白點對軸較清楚 | 拒絕繼續增加負柱鏡 |
| 加一小步後，又說兩次一樣 | 按拒絕處理，退回前一個設定 |

需要時把口頭編號「1、2」改「3、4」，避免只是慣性回答。非受測眼**由遮蓋片擋住，眼睛自然睜開**，不用自己用力閉眼；放輕鬆比較，減少不穩定反應。

這頁在講**度數判讀**。下一課找軸位的「追紅點」，則是轉柱鏡方向，不要混用。
''')
r.set(4,'b：方向先固定，只問力量夠不夠','''
> [!big] 在剛找到的粗略軸，逐次試多 −0.25 D。

| 動作 | 看病人反應 |
|---|---|
| JCC 點對粗略軸，再翻片 | 紅點對軸是否較清楚？ |
| 接受 | C 增加 −0.25 D，重新比較 |
| 拒絕 | 不再往負加；退回確認 |
| 第一次一樣 | 按下一頁的包夾確認，不一直往下加 |

**終點是最後一次接受的度數**，或第一次相同、且下一小步已被拒絕的位置。每累計 −0.50 DC，要配＋0.25 DS 補償；本課後面會算。
''')
r.set(5,'包夾法：走過頭一次，才知道前面是終點','''
> [!big] Bracketing＝一邊試過頭，再退回包住答案。

假設目前 C＝−1.00 D，翻片第一次說一樣：

| 下一輪 | 判斷 |
|---|---|
| 試 C＝−1.25 D，白點對軸較清楚或又一樣 | 這次多了，退回 **−1.00 D** |
| 試 C＝−1.25 D，紅點對軸較清楚 | 前次可能還不是終點，繼續小步確認 |

負柱鏡儀器裡，「更多」就是數字更負：−1.00 → −1.25。**不要把「減少 −0.25」誤寫成再往負加。**

連續兩次都選紅點對軸，C 累計多 −0.50 D；連續兩次白點對軸，C 少 −0.50 D。還要同步檢查球面補償。
''')
r.set(6,'為什麼改散光，要同時補球面？','''
> [!big] 改 C，兩方向的平均也會變；補 S 是把平均拉回。

之前調球面，是讓小燈在視網膜形成的**圓形光斑（COLC）**位於合適位置。新增負柱鏡會改平均對焦，不只改散光差距。

| C 怎麼變 | 平均 S＋C/2 的變化 | S 反向補 |
|---|---|---|
| −1.00 → −1.50，多 −0.50 D | 少 0.25 D | {g:加＋0.25 DS} |
| −1.50 → −1.00，少 −0.50 D | 多 0.25 D | {p:加 −0.25 DS} |

**DS 是球鏡度數，DC 是柱鏡度數。** 每次動 0.25 DC 時，課堂累計到 0.50 DC 再用 0.25 DS 補；最後仍需重查球面。
''')
r.set(7,'補償算一次：先算 C 變了多少','''
> [!big] C 變化一半，S 用相反號補。

原本 **S −2.50／C −2.00 D**，想把 C 減到 −1.50 D：

| 步驟 | 計算 |
|---|---|
| 1．C 的變化 | −1.50−(−2.00)＝＋0.50 D |
| 2．S 反向補一半 | −0.25 D |
| 3．新 S | −2.50−0.25＝**−2.75 D** |
| 4．舊平均 | −2.50＋(−2.00)/2＝−3.50 D |
| 5．新平均 | −2.75＋(−1.50)/2＝−3.50 D |

平均沒變，就是 **Sp Eq／SE 不變**。光學上，加負柱鏡使對焦位置往後，正球鏡把平均拉回；少用負柱鏡則反過來。

正柱鏡處方也用同一個算式 **ΔS＝−ΔC/2**，不必再背一套相反加減。
''')
r.save()

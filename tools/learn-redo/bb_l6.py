from optometry_common import *
r=Rewrite('optom2-u4-bb','l6')
r.set(0,'選方法：先查可不可以公平比較','''
> [!big] 兩眼視力、調節與融像能力，決定比較方式。

| 病人條件 | 課堂優先考慮 |
|---|---|
| 兩眼最佳視力接近 | 可用垂直稜鏡模糊比較 |
| 稍不等、弱視但可回答紅綠 | 稜鏡分離紅綠／改良Humphriss |
| 遠視、屈光不等、隱性震顫 | 評估完整雙眼驗光 |
| 已無實質調節 | 不必為調節再硬做平衡 |

這是選法地圖，不是只看到某病名就跳過檢查；還要確認視標看得見、答案穩定。
''')
r.set(1,'視力不等，和度數不等，是兩個問題','''
> [!big] 比模糊度要求視力相近；比每眼紅綠則不必把兩眼硬拉平。

| 條件 | 方式／原因 |
|---|---|
| 視力不等 | 紅綠類比同一眼內兩色；需有可靠反應 |
| 屈光不等 | 保融像的雙眼驗光可評估，不直接輪流遮蓋硬比 |
| 記憶弱 | 垂直稜鏡可同時比兩行，不必記前次 |
| 色覺異常 | 仍可試紅綠，因為比清晰度 |
| 病變造成明顯最佳視力差 | 不用加鏡片硬造出一樣糊 |
| 約60歲、無調節的課堂情境 | 調節平衡必要性低；判斷看能力，不只年齡 |

懷疑兩眼對焦需求不等造成清晰差，可考慮稜鏡紅綠確認；不能先假定視力差一定只是調節。
''')
r.set(2,'左右反應跳來跳去：別無限加鏡追答案','''
> [!big] 先排測量不穩，再依課堂原則讓主導眼稍清楚。

| 先確認 | 可能問題 |
|---|---|
| 有沒有盯住同一視標 | 亂轉眼、疲勞、理解錯指令 |
| 兩眼都看得到嗎 | 抑制、視力差、分離量不適合 |
| 球面小步確認是否穩 | 不要反覆大幅增加正負 |

若仍無法完全平衡，課堂／題型採**利眼稍清晰**，不硬逼相同。**優勢眼（dominant eye）**指觀看較主導；「優眼」有時指視力較好，題目用詞要看脈絡，兩者不必然同一眼。
''')
r.set(3,'平衡後的終點，還是最佳視力下最少負','''
> [!big] 兩眼差值先保留，再一起去掉霧視。

| 接著做 | 保留什麼？ |
|---|---|
| 移除稜鏡或分離工具 | 回到共同視標 |
| 雙眼同量減正／加負 | 保留剛調好的左右球面差 |
| 做雙眼MPMVA | 最佳視力下最多正、最少負 |

平衡只表示比較條件下接近一致，可能兩眼都還霧著、過正或過負，**不等於完全矯正**。它也不測隱斜位量；眼位問題須另行評估。
''')
r.set(4,'把完整流程串回來：每眼做完才換眼','''
> [!big] 球面 →軸 →度數 →球面 →平衡 →雙眼終點。

| 段落 | 做什麼？ |
|---|---|
| 起點 | 檢影／其他他覺結果 |
| 右眼MSR | 初始球面 →紅綠確認 →JCC先軸後度數 →第二次球面 |
| 左眼MSR | 同樣完整做一輪 |
| 兩眼一起 | 選合適平衡法 →共同去霧 →雙眼MPMVA |

這張表是**單眼MSR後接平衡**的路線；完整雙眼驗光是前課另一條路，不把兩套流程混搭成同義詞。
''')
r.set(5,'排序題：先看名稱，再對題目編號','''
> [!big] 編號只是選項代號，真正要懂的是工作順序。

| 107生普40的題號代碼 | 工作 |
|---|---|
| ② | 檢影 |
| ③ | 初始球面 |
| ① | 散光軸 |
| ④ | 散光度數 |
| ⑥ | 第二次球面 |
| ⑤ | 雙眼平衡 |

所以順序 **②③①④⑥⑤**。單眼段課堂可有紅綠確認；老師不建議第二次MPMVA單靠紅綠當終點，但部分考古題列它為選項，仍要看來源脈絡。最後別漏雙眼一起確認MPMVA。
''')

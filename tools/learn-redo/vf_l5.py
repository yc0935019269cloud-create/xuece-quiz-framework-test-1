from optometry_common import *
r=Rewrite('optom2-u3-vf','l5')
r.set(0,'FDT：不看小白點，改看閃爍條紋','''
> [!big] 測能不能察覺明暗交替的條紋，常用於快速篩檢。

**FDT＝frequency doubling technology，雙倍頻視野。** 它用一小塊閃爍條紋，改對比看病人能否察覺，和SAP的小白光點不同。

| 名詞 | 白話 |
|---|---|
| Flicker | 明暗快速交替，閃爍 |
| M／magnocellular 路徑 | 大細胞相關通道，對快速變化較敏感 |
| 對比敏感度 | 條紋和背景差多小，仍分得出來 |

課堂以M路徑連結青光眼篩檢。這是功能上的連結，**不能說只測M細胞，或每位早期青光眼一定先傷M**。
''')
r.set(1,'時間、度數與缺損：記住適用條件','''
> [!big] 可快速篩檢，也可完整測閾值；時間取決於程式。

| 課堂重點 | 怎麼讀？ |
|---|---|
| FDT約5～6分／眼，傳統Humphrey約15～20分 | 講義的程式比較，不能當所有新策略固定時間 |
| 屈光誤差≤6.00 D | 低空間頻率視標較不易受模糊影響，不表示完全零影響 |
| >6.00 D | 按檢查要求戴適當眼鏡 |
| 輸入年齡 | 與同齡常模比較 |
| 課堂缺損判準 | 2個相鄰區域異常，且重測2次仍一致 |

課堂亦以近線性關聯描述缺損與M相關功能／萎縮的關係；這不是所有病人的固定比例，不能取代完整青光眼診斷，也不是單次FDT異常就確診。
''')
r.set(2,'「雙倍頻」：看起來條紋密一倍','''
> [!big] 條紋數量沒真的增加，是快速交替造成的視覺現象。

| 先拆單位 | 具體意思 |
|---|---|
| 1 cycle | 一條亮帶＋一條暗帶，一組 |
| c/deg（cycle/degree） | 每1°視角有幾組，越大越密 |
| Hz | 每秒交替幾次；25 Hz是每秒25次 |

第一代用約 **0.25 c/deg** 的正弦光柵，亮暗平滑變化；以約 **25 Hz** 交替時，可能看成約 **0.50 c/deg**，就是**雙倍頻錯覺**。

注意這裡的「倍」指看起來的**空間條紋密度**，不是把時間的25 Hz變成50 Hz。
''',image=True)
r.set(3,'第一代與 Matrix：規格放在一起比較','''
> [!big] 換一代儀器，測點與視標就可能不同。

| 規格 | 第一代FDT | 第二代Humphrey Matrix |
|---|---|---|
| 空間頻率 | 0.25 c/deg | 0.5 c/deg |
| 區塊／大小 | 常見17區，每區約10° | 視程式約2°～5°，更細 |
| 程式測點 | 依第一代篩檢配置 | 30-2：69；24-2：55；10-2：44；macula：16 |

這些是課堂指定配置，不是所有FDT程式都17點。題目先認**哪一代、哪個程式**，再選數字。
''')
r.set(4,'VR：把測量空間放進頭戴裝置','''
> [!big] 不用靠在大碗前，但仍需要穩定注視與合適校正。

| 可能優點 | 需要評估的限制 |
|---|---|
| 可攜、較省空間 | 頭戴裝置有重量 |
| 姿勢較自由、較舒服 | 頭頸部受傷者可能不適合 |
| 可有成本效益 | 價格與效能依產品，不能一律稱更便宜 |

舒服可能讓反應較穩，但**不自動保證準確度更高**；還要看裝置、程式、病人與比較研究。
''')
r.set(5,'VR 產品與研究：不要把單篇結果變保證','''
> [!big] 「研究中相當」不等於所有VR都可互換。

課堂列的產品例：**Virtual Field、Vivid Vision、VisuALL、C3 Field Analyzer**。

| 課堂描述 | 讀法 |
|---|---|
| 部分研究可信度與SAP相當或更好 | 限該裝置、研究對象與策略 |
| 傳統儀器固定姿勢較累 | 疲勞會影響反應，應安排舒適定位與休息 |
| VR較符合人體工學 | 是潛在優點，仍須檢查戴合與眼位 |

考點先記可攜、省空間、舒適與重量限制；追蹤病人時，不隨意把不同儀器數字當同一尺度。
''')
r.set(6,'微視野：把哪裡看不見，疊回眼底照片','''
> [!big] 同時知道「功能多好」和「網膜哪一處」。

**Microperimetry（微視野）**將局部敏感度測量對應到**眼底影像**，以中央黃斑為主。

| 工作 | 意思 |
|---|---|
| 紅外線IR追蹤 | 眼睛小幅移動時，幫忙維持刺激對到原網膜位置 |
| 測局部敏感度 | 這個位置要多強刺激才察覺 |
| 測注視穩定度 | 眼睛是否持續用同一位置盯住目標 |
| 疊在眼底圖上 | 直接把弱點與病變位置對照 |

課堂流程提到最後拍眼底照；實際影像取得方式依儀器。它比只有方格表快篩更精密。
''',image=True)
r.set(7,'微視野用在哪？也要留意學習效應','''
> [!big] 能追蹤注視，不代表第一次做就完全沒有學習影響。

| 名詞／用途 | 白話 |
|---|---|
| AMD | 年齡相關性黃斑部病變 |
| DME | 糖尿病黃斑水腫 |
| 中、晚期青光眼 | 觀察剩下的中央功能等情境 |
| BCVA | 最佳矯正視力，只代表中央分辨字的表現 |

局部敏感度與注視可補充BCVA，某些研究對日常生活品質更有解釋力；部分研究也能比SAP更早察覺特定功能損傷。時間與點數依程式，課堂比較為點較少、耗時較長。

> [!warn] 修正舊教材的絕對說法
> 原寫「沒有學習效應」過度概括。研究可見第一次與第二次改善；仍需要示範、練習與重複檢查（Wu等，2013，PMID 24135753）。
''')
r.save()

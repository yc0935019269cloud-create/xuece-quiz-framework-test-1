from optometry_common import *
r=Rewrite('optom2-u2-msr','l3')
r.set(0,'找散光：看線，或比較翻片前後','''
> [!big] 要找的有兩件事：方向（軸位）和力量（度數）。

| 工具 | 病人看什麼？ | 適合先記的用途 |
|---|---|---|
| {b:裂孔板／裂隙片 Stenopaic slit} | 透過一條窄縫，轉動找清楚方向 | 分別測兩主子午線；不規則散光可用 |
| {o:鐘面圖／扇形圖} | 哪組放射線較黑、較清楚 | 不必記住兩張先後影像 |
| {g:JCC 交叉圓柱鏡} | 翻片前、後哪次較清楚 | 細修軸位與度數；軸可細到約 1～2° |

先知道這三種工具的差異，後面再逐一學擺位。
''')
r.set(1,'方法怎麼選：先看病人能完成哪種比較','''
> [!big] 不要把「操作比較粗」和「所有方法的精度排名」混成一件事。

| 情況 | 選法／順序 |
|---|---|
| 不規則散光 | 裂孔板可先找較清楚方向 |
| 不易記住前一張影像 | 鐘面或扇形圖，不硬用 JCC |
| 裂孔板測量 | 轉到清楚方向 → 該方向 MPMVA → 轉 90° 測另一方向 → 畫兩方向度數 → 合成處方 |
| 圖表方向刻度 | 鐘面相鄰線組約 30°；扇形常約 15° |

**MPMVA**：在最好視力下選最多正球鏡／最少負球鏡。**Power cross（屈光十字）**：用十字記互相垂直兩方向的度數。

國考比較精度的題型記 **JCC ＞裂孔板＞鐘面圖（106 生普 42）**。JCC 不穩時也可用扇形圖協助控制調節，不代表病人一定適用同一種方法。
''')
r.set(2,'手持 JCC：把鏡片拿到試鏡架前','''
> [!big] 鏡片不用固定在大儀器裡，也能翻給病人比。

::: cols b o
### 自由空間驗光
病人戴**試鏡架**，驗光師加試片，再拿手持 JCC 放前面比較。
適合沒有綜合驗光儀的場合。
|||
### 低視力者
可能需要轉頭或用視網膜旁邊的位置看（偏心注視）。
大儀器會擋姿勢與視野，試鏡架較自由。
:::

**低視力**是矯正後仍看不佳；微小的清楚差別可能感覺不到。因此可選較強的 JCC，讓翻片的差別大一點。
''')
r.set(3,'±0.25 D：不是兩片都加 0.25','''
> [!big] JCC 一個方向加正、垂直方向加同量負。

例如 **±0.25 D JCC**：兩條互相垂直的主子午線，力量分別是＋0.25 和 −0.25 D；翻過來就交換。

| 工具／情況 | 常見選擇 |
|---|---|
| 綜合驗光儀 | ±0.25、±0.37 D；部分有 ±0.50 D |
| 手持式 | ±0.25、±0.50、±1.00、±1.50、±2.00 D 等 |
| 視力好 | ±0.25 D 常足夠 |
| 低視力、差別難辨 | 可用 ±1.00 或 ±1.50 D 等較強鏡片 |

散光較高（題型常提 >1 D）或視力差時，±0.25 D 可能不易分辨，依實際反應選。鏡片可用紅／白點，亦有綠／黑等標法，先確認儀器定義。
''')
r.set(4,'紅點是負柱鏡的「軸」，不是最負力量方向','''
> [!big] 軸上不加該柱鏡的力量；完整力量在垂直方向。

先拆 JCC：等量的**正柱鏡＋負柱鏡**，兩個軸互相垂直。

| 標記 | 表示哪個軸？ | JCC 在這方向的合計力量 |
|---|---|---|
| {r:紅點} | 負柱鏡軸 | 正（＋） |
| 白點 | 正柱鏡軸 | 負（−） |

為什麼紅點反而正？紅點那條線上，**負柱鏡本身出力是 0**，卻收到垂直軸那片正柱鏡的力量。

例如 ±0.25 D：紅點方向＋0.25 D，白點方向 −0.25 D。用負柱鏡處方寫是 **＋0.25／−0.50 ×紅軸**。
''')
r.set(5,'把 JCC 寫成處方：先畫兩方向力量','''
> [!big] 先判正負力量，再看哪條焦線在前、在後。

| ±0.37 D JCC，紅點在 90° | 記法 |
|---|---|
| 90° 子午線 | 約＋0.37 D |
| 180° 子午線 | 約 −0.37 D |
| 負柱鏡寫法 | 講義採＋0.37／−0.75 ×90 |

**精度提醒**：常稱 ±0.37 的規格，名目值可指 ±0.375；完整差值為 0.75 D。若真的拿顯示的 0.37 精算，兩倍是 0.74，不能寫成 0.37×2＝0.75。理想等量正負的 SE＝0，四捨五入處方會有微小差。

| 判焦線的規則 | 例如紅點水平 |
|---|---|
| 加正的子午線先聚焦 | 水平先收好光 |
| 焦線方向與該子午線垂直 | 所以前方留下垂直焦線 |

白點水平則水平力量較負，**後方**為垂直焦線；垂直方向先聚焦，**前方**為水平焦線。白點垂直時，後方是水平焦線。
''')
r.set(6,'旋轉與翻轉：先決定怎麼擺，再比較','''
> [!big] 旋轉找擺位；翻轉比較同組方向的正負交換。

::: cols b o
### 旋轉 Rotate
在眼前轉一個角度。
紅白點所在的**方向線**一起改變，用來對準或跨在處方軸兩側。
|||
### 翻轉 Flip
同一片 JCC 翻給病人看第 1 次、第 2 次。
比較用的方向線保留，**哪條加正、哪條加負交換**。
:::

先把**最佳／初始球面**找好，再用 JCC。否則病人可能在比整體失焦，無法專心比散光差異。實際看的是哪個更清楚，不是紅白點的顏色。
''')
r.set(7,'先軸後度數：別一次改兩件事','''
> [!big] 先讓方向正確，再決定那個方向要補多少。

| 步驟 | 暫時固定什麼？ | 比什麼？ |
|---|---|---|
| 找軸位 | 先保留目前柱鏡度數 | 哪個方向清楚 |
| 找度數 | 固定剛找好的軸 | 多一點／少一點柱鏡哪個清楚 |

度數還沒完美時仍可細修軸。綜合驗光儀的 JCC 可能隨柱鏡軸一起轉，注意辨認「轉方向」和「翻片」兩個動作。

若起初沒有柱鏡，JCC 在 **90/180°** 一組翻片相同，在 **45/135°** 一組也相同，才支持不需新增可測出的規則散光；只試一組不能直接下結論。
''')
r.save()

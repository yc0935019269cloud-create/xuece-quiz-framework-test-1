from optometry_common import *
r=Rewrite('optom2-u3-vf','l2')
r.set(0,'對坐視野：用你的正常視野當對照','''
> [!big] 不用大儀器，先看病人有沒有少掉大片範圍。

**Confrontational VF（對坐／比較性視野）**：病人和檢查者面對面，固定對看，再比較能否看到中間的手指。

| 準備 | 課堂設定 |
|---|---|
| 距離 | 兩人約1公尺 |
| 手放哪 | 兩人中間、與雙方距離相近 |
| 病人眼鏡 | 取下，避免鏡框擋周邊 |
| 分兩部分 | 四象限數手指 →若異常，再找邊界 |

可以快篩半側盲、象限盲、嚴重青光眼等大缺損；不是精密量出每點敏感度。
''')
r.set(1,'正常快篩，不等於排除早期疾病','''
> [!big] 能抓大片缺損；細小、早期缺損可能漏掉。

| 它能做 | 它做不到的事 |
|---|---|
| 數手指：四區能否辨認 | 精確量每點閾值 |
| 移動手指：大概邊界在哪 | 可靠排除早期青光眼 |
| 跟檢查者比較 | 在檢查者視野也異常時，當成正常標準 |

**敏感度低**在這裡指「抓出疾病的能力有限」，不是說病人視網膜一定不敏感。可疑結果要做更精細的視野檢查。
''')
r.set(2,'測右眼時：病人右眼對你的左眼','''
> [!big] 兩隻正對著的眼睛保持注視，不能追手指。

| 順序 | 動作／指令 |
|---|---|
| 1 | 病人遮左眼 OS，測右眼 OD |
| 2 | 檢查者閉右眼 OD，留左眼和病人右眼對看 |
| 3 | 先說「看我的鼻子，臉有沒有哪處看不到？」約查中央10～15° |
| 4 | 改說「一直看我睜開的眼睛」 |
| 5 | 在鼻上、鼻下、顳上、顳下四區比手指，請他數 |

換測左眼時，遮蓋與注視眼也跟著對換。檢查者邊測邊看病人有沒有偷轉眼。
''')
r.set(3,'數手指：用容易分辨的數量','''
> [!big] 看的是哪一區沒察覺，不是讓病人猜數字。

| 操作細節 | 為什麼？ |
|---|---|
| 比1、2、4根；課堂不用3根 | 減少看糊後混淆 |
| 兩手可同時在不同區比不同數字 | 比較兩側，也可察覺同時刺激時忽略一側 |
| 持續提醒盯你的眼睛 | 轉眼去看手，就失去固定視野的比較 |

小視標或小白球也可用，但病人仍固視；找邊界時從**周邊看不到處往中央**移，不是從中央往外跑。
''')
r.set(4,'有一區數不到：把手慢慢移進來','''
> [!big] 從看不到處進入，記第一次看見的位置。

::: flow
病人固定看你的眼睛
擺動手指放到該側周邊、看不到處
慢慢往中央移，大小與距離盡量固定
病人一看到動作就說；記大致邊界
:::

也可用直徑 **≤3 mm** 小視標／小白球，依檢查距離保持標準化。這是在篩檢察覺能力，並不需要靠近用處方讀小字。

紀錄至少寫**哪眼、哪區、完整或受限**，不要只寫「視野異常」。
''')
r.set(5,'FCF：把一句英文拆成三個資訊','''
> [!big] FCF OD；OS limited superior temporal＝右眼完整，左眼顳上受限。

| 字詞 | 意思 |
|---|---|
| FCF／full to finger counting | 數手指快篩各區完整 |
| OD／OS | 右眼／左眼 |
| Limited | 受限 |
| Superior temporal | 上方＋顳側，合起來是顳上象限 |

FCF 常亦用來指 finger counting field，重點是交代方法與範圍，不暗示完整自動視野正常。

發現受限→進一步視野檢查，依形狀協助定位。舊教材小白球「眼前5 cm」未清楚交代是距誰，**不把它當病人眼前5 cm的操作要求**；課堂設置的刺激面仍是兩人中間。
''')
r.save()

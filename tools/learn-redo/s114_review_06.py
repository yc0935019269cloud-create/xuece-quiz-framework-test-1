from s114_review_common import *
r=Review('keratometry-p2')
r.intro=dict(type='intro',title='角膜像一面彎鏡：先量彎度，再推K值',body=['> [!big] K值是從角膜曲率估出的力量，不是全眼近視度數。','','依序整理半徑與K、角膜散光方向、眼內／殘餘散光，以及儀器與地圖的限制。每個算式先分清量的是角膜還是全眼。'])
r.set(0,'半徑小＝彎得急＝較陡，K值較大','''
> [!big] r是幾何長度；K是用公式估計的角膜屈光力。

想像大球與小球的表面：小球局部彎得較急，曲率半徑r較小。角膜較陡時，傳統K值通常較大。

| 符號／公式 | 怎麼記？ |
|---|---|
| r | 半徑，mm |
| K | 估算角膜力量，D |
| K＝337.5/r | 半徑在分母，越小K越大 |
| r＝337.5/K | 反算半徑 |

公式採**角膜曲率換算指數1.3375**，是儀器的假設有效指數，不是說真實角膜材料折射率就是1.3375。半徑7.5～8 mm附近，差0.1 mm約差0.5 D是粗估，精算用公式。
''')
r.set(1,'先算一條K，再算另一條；差值才是角膜散光','''
> [!big] 45 D不表示近視4500度，它是角膜本身的收光估值。

| 已知 | 算法 | 結果 |
|---|---|---|
| r7.50 mm | 337.5/7.50 | 45.00 D |
| r7.00 mm | 337.5/7.00 | 約48.2 D |
| K46.00 D | 337.5/46 | 約7.34 mm |
| K43.83 D | 337.5/43.83 | 約7.70 mm |

若兩主方向45和43 D，角膜散光量約**2.00 D**。要寫矯正柱鏡，還要看哪個方向較陡，不能只算差就忘記軸。
''')
r.set(2,'從較陡方向，轉90°找負柱鏡軸','''
> [!big] 強方向要減弱，負柱鏡軸就放在較平方向。

| K讀數 | 較強／陡方向 | 角膜負柱鏡形式 |
|---|---|---|
| 42.50@180／45.00@90 | 90°垂直，順規 | −2.50 DC×180 |
| 45.00@180／43.00@90 | 180°水平，逆規 | −2.00 DC×90 |

規則主方向互相垂直。15°與115°差100°，是題目判不規則的線索；臨床還須排操作、定位與角膜不規則，不單靠兩個角度就確診。

斜散光常見範圍30～60°、120～150°，留意題目講強方向還是負軸。**MCAR＝mires clear and regular**，指反射標像清楚、規則。
''')
r.set(3,'K讀數的@角度，是角膜那條線的位置','''
> [!big] @180最陡，不等於負柱鏡軸也要180。

以45.00@180／43.00@90為例：

1. 45比43大→水平角膜較強。
2. 差45−43＝2.00 D。
3. 負柱鏡在軸上不加力量，垂直軸才有完整負力。
4. 要減弱水平，就把負軸放**90°**，寫−2.00 DC×90。

若題目給半徑，先用r小→K大找較陡方向，再走同一套流程，不用另背一套相反口訣。
''')
r.set(4,'全眼散光減角膜散光：先確認方向','''
> [!big] 方向一致可直接減；方向不同，不能只減兩個大小。

全眼散光包含角膜前後表面及眼內因素。傳統K只從角膜前表面估計，**殘餘散光＝全眼−K估計角膜散光**，不等於全都來自水晶體。

| 同軸例 | 計算 |
|---|---|
| 全眼C−4.75×180 | 已知處方 |
| K42@180／45@90 | 角膜估計C−3.00×180 |
| 兩者同軸，相減 | −4.75−(−3.00)＝**−1.75×180** |

負柱鏡形式、參考平面與軸要先對齊。軸不同需要向量／屈光交叉分析，不能不管方向只做4.75−3。

K差與處方C大小接近、方向相同，支持主要由角膜貢獻；不是只看兩個數字相等就排除眼內因素。
''')
r.set(5,'Javal與簡易規則：題目指定哪個才用哪個','''
> [!big] 0.50 D逆規是帶方向的散光，不是任何C都固定加0.50。

| 課堂預測 | 例子 |
|---|---|
| 簡易規則：順規全眼約比角膜少0.50 D | 角膜−2.25×180 →全眼約−1.75×180 |
| Javal：角膜散光×1.25，再合成0.50 D逆規 | 角膜逆規2.00 D →1.25×2＋0.5＝3.00 D逆規，即−3.00×90 |

若Javal用在順規例，加入逆規項可能是**抵消**，不是把大小通通相加；斜軸需保留方向。它們是預測，不代替實際全眼驗光。

這也解釋為什麼角膜散光和處方C不一定一樣：還有角膜後表面與眼內貢獻。
''')
r.set(6,'角膜弧度儀與角膜地圖：看得到哪裡？','''
> [!big] 傳統K看前表面中央小區域；地圖較廣，但不是包辦全部角膜結構。

| 工具／名詞 | 工作與限制 |
|---|---|
| Keratometer，角膜弧度儀 | 由前表面反射標像估中央約3 mm區域，不是全角膜或只量一個頂點 |
| 換算假設 | 局部曲率規則、有效指數1.3375，不能直接分離後表面或水晶體散光 |
| 常見量程 | 約36～52 D；輔助鏡如課堂−1.00 DS可擴展，照機型換算 |
| mires反射標像扭曲 | 淚膜不穩、乾燥、翼狀胬肉、圓錐角膜等可能干擾 |
| Placido同心環地形圖 | 以前表面反射環重建較廣區域；同條件環距近常較陡 |
| Sim K | 由地圖估類似傳統K的值，不等於全眼散光 |

調節主要改水晶體，傳統K較不受它直接影響，但不等於所有測量誤差都沒有。高K＋扭曲標像＋不規則散光→需懷疑圓錐角膜並進一步評估，不能單憑一項確診。

Placido不是直接量整個角膜後表面、厚度或全部角膜；要分清前表面地形圖與其他斷層測量。
''')
r.save()

from optometry_common import *
r=Rewrite('optom2-u4-bb','l2')
r.set(0,'先看最常用骨架：霧視、比較、再看清楚','''
> [!big] 模糊比較時，清楚那眼加正；平衡後，兩眼一起去霧。

以下是**比較兩眼模糊程度**的方法骨架；Humphriss等各有不同呈現方式，後面分開教。

| 順序 | 做什麼？ |
|---|---|
| 1 | 雙眼先各加約＋0.75～＋1.00 D霧視 |
| 2 | 用稜鏡、遮蓋等分辨哪個影像來自哪眼 |
| 3 | 問哪個較清楚 |
| 4 | 較清楚那眼加＋0.25 DS，重新比 |
| 5 | 兩眼最接近一樣後，移除分離工具 |
| 6 | 兩眼等量去霧，找雙眼MPMVA |

霧視是暫時加正讓遠方糊一些，不是永久增加遠視處方。
''')
r.set(1,'為什麼不在模糊那眼一直加負？','''
> [!big] 此時要維持放鬆比較，不要用負鏡刺激另一眼追上。

假設霧視後，右眼字仍較清楚、左眼較糊：

| 操作 | 原因 |
|---|---|
| 右眼加＋0.25 D | 把較清楚眼也帶到相近霧視程度 |
| 再比較 | 接近相同，才支持球面需求接近平衡 |
| 不在左眼一路加負 | 避免讓調節介入、失去原本霧視比較條件 |

課堂霧視常約 **20/40～20/50**。兩眼原本最佳視力要相近，這種清楚度比較才有意義；不能只憑哪眼較清楚，就斷言那眼調節實際多用了幾D。

霧視不是越多越好，糊到無法比就失去用途。
''')
r.set(2,'選方法先問：還有共同影像嗎？','''
> [!big] 分離中央視標，不一定得把全部融像都拿掉。

| 分組 | 方法 | 白話 |
|---|---|---|
| 無融像 | 垂直稜鏡分離、交替遮蓋 | 兩眼影像分開或輪流看，少了共同定位 |
| 保有融像 | Humphriss、雙眼驗光、偏光、隔板 | 中央可分開處理，周邊仍有共同線索 |
| 視力不等時 | 稜鏡分離紅綠等 | 每眼各比紅綠，不比兩眼字誰清楚 |

有融像較接近日常雙眼觀看；不表示任何病人、任何器材都保證更準。
''')
r.set(3,'方法地圖：比的是哪一種差別？','''
> [!big] 兩眼最佳視力不等時，改用每眼內部的比較。

| 方法 | 兩眼怎麼分？ | 比什麼／主要條件？ |
|---|---|---|
| 垂直稜鏡 | 同時上下兩行 | 比兩行模糊程度；最佳視力相近 |
| 交替遮蓋 | 輪流看同一行 | 比前後兩眼；需要記住前次 |
| Humphriss | 一眼霧視，另一眼作答 | 每眼分別紅綠或球面比較；保周邊融像 |
| 稜鏡分離紅綠 | 上下各一組紅綠 | 各眼內部比紅綠；視力可不等 |
| 雙眼驗光 | 一眼霧視，另一眼完整驗 | 保有融像；課堂要求兩眼≥20/25 |
| 偏光／隔板 | 每眼看不同部分 | 保共同周邊融像，依視標比較 |

**Turville、Morgan**是保有雙眼觀看的相關中隔方法名。立體視測試在測深度知覺，不等於雙眼平衡。
''')
r.set(4,'不適合某方法，不代表完全不能驗光','''
> [!big] 方法造成問題時，換保留融像、可完成比較的方法。

| 病人條件 | 為何要小心？ |
|---|---|
| 遠視 | 調節可能藏住部分正度數，需要更穩定控制 |
| 隱性眼球震顫 | 遮眼／分離可能讓眼動加重 |
| 屈光不等 Anisometropia | 兩眼度數不同，輪流比較可能不穩 |
| 最佳視力不等 | 不宜硬用霧後同樣清楚當終點 |

課堂把遠視、震顫列為垂直稜鏡、交替遮蓋及所教Humphriss流程的限制，建議評估**完整雙眼驗光**。這是課堂方法選擇，不把「遠視」當所有平衡技術的絕對禁忌。
''')
r.set(5,'選法速記：視力差、度數差、紅綠反應分開問','''
> [!big] 不同的「兩眼不一樣」，限制不同。

| 條件 | 課堂選擇 |
|---|---|
| 兩眼最佳視力不等，例如1.0／0.8 | 稜鏡分離紅綠、改良單眼霧視Humphriss；不能硬比模糊度 |
| 屈光不等 | 避免直接用交替遮蓋當可靠平衡依據 |
| 遠視、假性近視、隱性震顫、雙眼視問題 | 評估保留融像的雙眼自覺式驗光 |
| 紅綠清晰度分不出來 | 不強用紅綠法 |
| 色覺異常 | 仍可能做紅綠，因比清晰度而非辨色 |

嚴重病變、視力差很大時，先處理能否比較與病因；不是看到不等，就一律指定某個平衡法。
''')
r.save()
